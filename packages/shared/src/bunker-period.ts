/**
 * Периоды бункера и шкала полноты (срез F «норма-факт», задача 2).
 *
 * ЗАЧЕМ ЭТОТ МОДУЛЬ СУЩЕСТВУЕТ. Норме верить можно: она сходится с закупками
 * по счетам-фактурам на 95% (задача 1, `./norm.ts`). Факту — нет: 1143 из 1153
 * заливок в журнале восстановлены ретро-разбором телеграм-переписки, и треть
 * визитов в ней не распозналась. Значит «норма минус факт» сегодня измеряет
 * ПОЛНОТУ ЖУРНАЛА, а не расход сырья. Выдать вердикт на неполном периоде —
 * значит обвинить в недостаче 30–56% КАЖДУЮ точку, где просто не вели записи.
 *
 * Поэтому `периодБункера` — не про арифметику разницы, а про то, ИМЕЕМ ЛИ МЫ
 * ПРАВО эту разницу считать. `полнота` здесь — не побочный флаг для витрины,
 * а несущая конструкция: `разница` заполняется ТОЛЬКО когда
 * `полнота === "полный"`, во всех остальных случаях — `null`.
 *
 * ЦИФРЫ РАЗВЕДКИ (подтверждают шкалу на живых данных). Из 885 пар
 * «заливка → возврат» посчитаны только 447. Отброшены:
 *   - 282 — возврат тяжелее заливки        → `"тара не откалибрована"`;
 *   - 42  — позиция без однозначного ингредиента → `"позиция неоднозначна"`;
 *   - 11  — нет тары (бункер не размещён)  → `"нет размещения"`;
 *   - 103 — нет нормы за интервал          → `"нормы нет"`.
 *   (282 + 42 + 11 + 103 = 438 = 885 - 447 — сходится.)
 *
 * САМАЯ МАССОВАЯ ПРИЧИНА — 282 пары «возврат тяжелее заливки». Это НЕ
 * отрицательный расход, а сломанная тара (у одной позиции медиана нетто
 * вообще 14 г, 42 заливки из 90 дают ноль или минус). Молчаливый минус здесь
 * дал бы «перерасход» с обратным знаком — витрина показала бы, что автомат
 * ПРОИЗВЁЛ сырьё. Поэтому нетто «залито минус возвращено» никогда не выдаётся
 * как расход напрямую при таком раскладе — это отдельное состояние полноты,
 * а не число со знаком минус, потерянное в отчёте.
 *
 * ПОРЯДОК ПРОВЕРОК. `полнота` — одно значение, не множество, поэтому нужен
 * приоритет: от самой фундаментальной причины к самой частной.
 *   1. нет размещения       — бункера на этой позиции физически не было;
 *   2. нет заливки           — в журнале нет записи заливки за период;
 *   3. нет возврата          — в журнале нет записи возврата за период;
 *   4. тара не откалибрована — числа есть, но противоречат друг другу
 *      (возврат > заливки) — это проблема измерения, проверяется раньше,
 *      чем метаданные об ингредиенте и норме;
 *   5. позиция неоднозначна  — числа сходятся, но неизвестно, к какому
 *      ингредиенту (а значит, и к какой норме) их приводить;
 *   6. нормы нет             — ингредиент известен, а нормы на интервал нет
 *      (задача 1: `normFor`/`parseNormRecipe` не дали значения);
 *   7. полный                — все предыдущие условия сняты, разница
 *      осмысленна.
 *
 * `факт` (= залито − возвращено) считается ВСЕГДА, даже в отброшенных
 * состояниях — как сырое число для отладки и объяснения витрины «почему
 * отброшено». Но это не расход: потребитель обязан смотреть на `полнота`
 * раньше, чем на `факт`, и брать `разница`, а не пересчитывать
 * `факт - норма` заново — иначе он тихо потеряет эту защиту.
 */

export type Полнота =
  | "полный"
  | "нет возврата"
  | "нет заливки"
  | "позиция неоднозначна"
  | "тара не откалибрована"
  | "нет размещения"
  | "нормы нет";

export interface ПериодБункера {
  machineId: string;
  position: number;
  ingredientId: string | null;
  from: string;
  to: string;
  залито: number;
  возвращено: number;
  факт: number;
  норма: number | null;
  чашек: number;
  полнота: Полнота;
  /** Разница считается ТОЛЬКО при полноте «полный». Иначе null. */
  разница: number | null;
}

/**
 * Вход одного периода бункера. Модуль чистый: сопоставление заливка↔возврат,
 * разрешение ингредиента позиции и поиск нормы за интервал — забота
 * следующей задачи (сборка из БД); здесь только вход → выход.
 */
export interface ВходПериодаБункера {
  machineId?: string;
  position?: number;
  /** Ингредиент позиции. В выдаче становится `null`, если `однозначна: false`. */
  ingredientId?: string | null;
  from?: string;
  to?: string;
  /**
   * Бункер физически размещён на автомате в этот период? По умолчанию `true`.
   * `false` — 11 пар разведки без тары: позиции физически не существовало.
   */
  размещена?: boolean;
  /**
   * Позиция однозначно сопоставлена одному ингредиенту? По умолчанию `true`.
   * `false` — 42 пары разведки: ноль или больше одного кандидата ингредиента.
   */
  однозначна?: boolean;
  /** Залито за период, г. `null` — заливка не зафиксирована в журнале. */
  залито: number | null;
  /** Возвращено за период, г. `null` — возврат не зафиксирован в журнале. */
  возвращено: number | null;
  /** Норма расхода на партию (задача 1, `normFor`), г. `null` — нормы за интервал нет. */
  норма: number | null;
  чашек: number;
}

/** Период бункера с оценкой полноты входных данных (порядок проверок — см. шапку файла). */
export function периодБункера(вход: ВходПериодаБункера): ПериодБункера {
  const machineId = вход.machineId ?? "";
  const position = вход.position ?? 0;
  const from = вход.from ?? "";
  const to = вход.to ?? "";
  const размещена = вход.размещена ?? true;
  const однозначна = вход.однозначна ?? true;
  const { залито: залитоВход, возвращено: возвращеноВход, норма, чашек } = вход;

  // Ингредиент в выдаче осмыслен только когда позиция однозначна — иначе он
  // не привязан ни к чему определённому (см. п.5 порядка проверок выше).
  const ingredientId = однозначна ? вход.ingredientId ?? null : null;

  const залито = залитоВход ?? 0;
  const возвращено = возвращеноВход ?? 0;
  const факт = залито - возвращено; // сырое число, см. шапку файла — само по себе не расход

  const базовый = { machineId, position, ingredientId, from, to, залито, возвращено, факт, норма, чашек };

  if (!размещена) {
    return { ...базовый, полнота: "нет размещения", разница: null };
  }
  if (залитоВход === null) {
    return { ...базовый, полнота: "нет заливки", разница: null };
  }
  if (возвращеноВход === null) {
    return { ...базовый, полнота: "нет возврата", разница: null };
  }
  if (возвращено > залито) {
    // Молчаливый минус здесь дал бы «перерасход» с обратным знаком — см. шапку файла.
    return { ...базовый, полнота: "тара не откалибрована", разница: null };
  }
  if (!однозначна) {
    return { ...базовый, полнота: "позиция неоднозначна", разница: null };
  }
  if (норма === null) {
    return { ...базовый, полнота: "нормы нет", разница: null };
  }

  return { ...базовый, полнота: "полный", разница: факт - норма };
}
