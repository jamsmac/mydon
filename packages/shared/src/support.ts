/**
 * Опора под цифрой: на скольких фактах стоит показатель (Н-3, Н-4).
 *
 * ЗАЧЕМ. Метод накопления («данные копятся из операций») имеет ровно один
 * крупный риск: посчитать на половине данных и выдать уверенно неверное число.
 * Так появился «минус 18 г сахара». Цифра без опоры хуже отсутствия цифры:
 * отсутствие видно, а неверная уверенность — нет.
 *
 * ЧЕГО НЕ ДЕЛАЕМ (Н-4). Порог доверия — НЕ порог сокрытия. Показатель виден
 * всегда; меняется не видимость, а сила формулировки. Спрятать слабую цифру
 * значит заставить человека искать её другим путём — и он найдёт, но уже без
 * пометки о слабости.
 *
 * Словарь один на всю систему: три слова, а не «примерно», «ориентировочно»,
 * «по неполным данным» в каждом отчёте по-своему.
 */

export type SupportStrength = "none" | "preliminary" | "stable";

/**
 * Граница «предварительно» → «устойчиво».
 *
 * Десять замкнутых фактов: на меньшем числе один промах (одно взвешивание не в
 * том состоянии, один пропущенный возврат) двигает среднее больше чем на
 * десятую, то есть больше порога расхождения, на котором мы поднимаем тревогу
 * (`RECONCILE_THRESHOLD_RATIO`). Цифра, которую переворачивает одна ошибка,
 * называться устойчивой не может — это и есть весь смысл числа 10.
 */
export const STABLE_FACTS = 10;

export interface Support {
  /** Сколько фактов реально сложилось в эту цифру. */
  facts: number;
  /** Сколько их могло быть всего (27 наборов, 8 бункеров…); null — не считаем. */
  of: number | null;
  strength: SupportStrength;
}

export function supportOf(facts: number, of: number | null = null): Support {
  const n = Number.isFinite(facts) && facts > 0 ? Math.floor(facts) : 0;
  const strength: SupportStrength = n === 0 ? "none" : n < STABLE_FACTS ? "preliminary" : "stable";
  return { facts: n, of: of === null || !Number.isFinite(of) ? null : Math.floor(of), strength };
}

export const SUPPORT_WORD: Record<SupportStrength, string> = {
  none: "нет данных",
  preliminary: "предварительно",
  stable: "устойчиво",
};

/**
 * Подпись рядом с цифрой: «предварительно, 3 заправки из 27».
 *
 * `unit` — что именно считали, в родительном множественном («заправки»,
 * «замера»): без этого «3 из 27» не отвечает на вопрос «три чего».
 */
export function supportLabel(s: Support, unit: string): string {
  if (s.strength === "none") return `${SUPPORT_WORD.none}: ни одного факта (${unit})`;
  const of = s.of === null ? "" : ` из ${s.of}`;
  return `${SUPPORT_WORD[s.strength]}, ${s.facts} ${unit}${of}`;
}
