import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { периодБункера } from "./bunker-period";

describe("Периоды бункера и шкала полноты (срез F, задача 2)", () => {
  it("возврат тяжелее заливки — не отрицательный расход, а «тара не откалибрована»", () => {
    // 282 пары из 885 такие (факт 5). Молчаливый минус тут дал бы отрицательный
    // расход и «перерасход» с обратным знаком на витрине.
    const p = периодБункера({ залито: 500, возвращено: 700, норма: 400, чашек: 50 });
    assert.equal(p.полнота, "тара не откалибрована");
    assert.equal(p.разница, null, "разницы нет там, где вход противоречив");
  });

  it("нет нормы за интервал — «нормы нет», а не недостача 100%", () => {
    const p = периодБункера({ залито: 500, возвращено: 100, норма: null, чашек: 0 });
    assert.equal(p.полнота, "нормы нет");
    assert.equal(p.разница, null);
  });

  it("полный период считает разницу", () => {
    const p = периодБункера({ залито: 780, возвращено: 250, норма: 500, чашек: 62 });
    assert.equal(p.полнота, "полный");
    assert.equal(p.факт, 530);
    assert.equal(p.разница, 30);
  });

  it("«факт» считается всегда, даже в отброшенном периоде — как сырое число для отладки", () => {
    // Тот же кейс «тара не откалибрована»: факт отрицательный и посчитан,
    // но разница остаётся null — потребитель обязан смотреть на полноту, а не
    // пересчитывать факт-норма сам.
    const p = периодБункера({ залито: 500, возвращено: 700, норма: 400, чашек: 50 });
    assert.equal(p.факт, -200);
    assert.equal(p.разница, null);
  });

  it("нет заливки — не недостача 100%, а «нет заливки»", () => {
    const p = периодБункера({ залито: null, возвращено: 100, норма: 400, чашек: 10 });
    assert.equal(p.полнота, "нет заливки");
    assert.equal(p.разница, null);
  });

  it("нет возврата — не полный расход, а «нет возврата»", () => {
    const p = периодБункера({ залито: 500, возвращено: null, норма: 400, чашек: 10 });
    assert.equal(p.полнота, "нет возврата");
    assert.equal(p.разница, null);
  });

  it("бункер не размещён (нет тары) — «нет размещения», проверяется раньше остальных", () => {
    // 11 пар разведки без тары. Флаг приоритетнее прочих — без размещения
    // заливка/возврат в принципе не относятся ни к чему.
    const p = периодБункера({
      залито: 500,
      возвращено: 100,
      норма: 400,
      чашек: 10,
      размещена: false,
    });
    assert.equal(p.полнота, "нет размещения");
    assert.equal(p.разница, null);
  });

  it("позиция без однозначного ингредиента — «позиция неоднозначна», ingredientId в выдаче null", () => {
    // 42 пары разведки: 0 или больше одного кандидата ингредиента.
    const p = периодБункера({
      залито: 500,
      возвращено: 100,
      норма: 400,
      чашек: 10,
      ingredientId: "какой-то-кандидат",
      однозначна: false,
    });
    assert.equal(p.полнота, "позиция неоднозначна");
    assert.equal(p.ingredientId, null, "неоднозначный ингредиент не прокидывается в выдачу");
    assert.equal(p.разница, null);
  });

  it("однозначная позиция прокидывает ingredientId в выдачу без изменений", () => {
    const p = периодБункера({
      залито: 780,
      возвращено: 250,
      норма: 500,
      чашек: 62,
      ingredientId: "кофе",
    });
    assert.equal(p.ingredientId, "кофе");
    assert.equal(p.полнота, "полный");
  });

  it("возврат равен заливке — нетто 0, это полный период (весь объём вернули), не «тара не откалибрована»", () => {
    const p = периодБункера({ залито: 500, возвращено: 500, норма: 400, чашек: 10 });
    assert.equal(p.полнота, "полный");
    assert.equal(p.факт, 0);
    assert.equal(p.разница, -400);
  });

  it("не размещённая позиция приоритетнее «тара не откалибрована» — числовое противоречие не проверяется вовсе", () => {
    const p = периодБункера({
      залито: 500,
      возвращено: 700,
      норма: 400,
      чашек: 10,
      размещена: false,
    });
    assert.equal(p.полнота, "нет размещения");
  });

  it("machineId/position/from/to по умолчанию — пустая строка/0, если не заданы", () => {
    const p = периодБункера({ залито: 780, возвращено: 250, норма: 500, чашек: 62 });
    assert.equal(p.machineId, "");
    assert.equal(p.position, 0);
    assert.equal(p.from, "");
    assert.equal(p.to, "");
  });
});
