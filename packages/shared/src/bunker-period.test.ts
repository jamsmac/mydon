import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { bunkerPeriod } from "./bunker-period";

describe("Периоды бункера и шкала полноты (срез F, задача 2)", () => {
  it("возврат тяжелее заливки — не отрицательный расход, а «тара не откалибрована»", () => {
    // 282 пары из 885 такие (факт 5). Молчаливый минус тут дал бы отрицательный
    // расход и «перерасход» с обратным знаком на витрине.
    const p = bunkerPeriod({ залито: 500, возвращено: 700, норма: 400, чашек: 50, тараОткалибрована: true, однозначна: true, размещениеПолно: true, чашекБезНормы: 0 });
    assert.equal(p.полнота, "тара не откалибрована");
    assert.equal(p.разница, null, "разницы нет там, где вход противоречив");
  });

  it("нет нормы за интервал — «нормы нет», а не недостача 100%", () => {
    const p = bunkerPeriod({ залито: 500, возвращено: 100, норма: null, чашек: 0, тараОткалибрована: true, однозначна: true, размещениеПолно: true, чашекБезНормы: 0 });
    assert.equal(p.полнота, "нормы нет");
    assert.equal(p.разница, null);
  });

  it("полный период считает разницу", () => {
    const p = bunkerPeriod({ залито: 780, возвращено: 250, норма: 500, чашек: 62, тараОткалибрована: true, однозначна: true, размещениеПолно: true, чашекБезНормы: 0 });
    assert.equal(p.полнота, "полный");
    assert.equal(p.факт, 530);
    assert.equal(p.разница, 30);
  });

  it("«факт» считается всегда, даже в отброшенном периоде — как сырое число для отладки", () => {
    // Тот же кейс «тара не откалибрована»: факт отрицательный и посчитан,
    // но разница остаётся null — потребитель обязан смотреть на полноту, а не
    // пересчитывать факт-норма сам.
    const p = bunkerPeriod({ залито: 500, возвращено: 700, норма: 400, чашек: 50, тараОткалибрована: true, однозначна: true, размещениеПолно: true, чашекБезНормы: 0 });
    assert.equal(p.факт, -200);
    assert.equal(p.разница, null);
  });

  it("нет заливки — не недостача 100%, а «нет заливки»", () => {
    const p = bunkerPeriod({ залито: null, возвращено: 100, норма: 400, чашек: 10, тараОткалибрована: true, однозначна: true, размещениеПолно: true, чашекБезНормы: 0 });
    assert.equal(p.полнота, "нет заливки");
    assert.equal(p.разница, null);
  });

  it("нет возврата — не полный расход, а «нет возврата»", () => {
    const p = bunkerPeriod({ залито: 500, возвращено: null, норма: 400, чашек: 10, тараОткалибрована: true, однозначна: true, размещениеПолно: true, чашекБезНормы: 0 });
    assert.equal(p.полнота, "нет возврата");
    assert.equal(p.разница, null);
  });

  it("бункер не размещён (нет тары) — «нет размещения», проверяется раньше остальных", () => {
    // 11 пар разведки без тары. Флаг приоритетнее прочих — без размещения
    // заливка/возврат в принципе не относятся ни к чему.
    const p = bunkerPeriod({
      залито: 500,
      возвращено: 100,
      норма: 400,
      чашек: 10,
      тараОткалибрована: false,
      однозначна: true, размещениеПолно: true,
      чашекБезНормы: 0,
    });
    assert.equal(p.полнота, "нет тары");
    assert.equal(p.разница, null);
  });

  it("позиция без однозначного ингредиента — «позиция неоднозначна», ingredientId в выдаче null", () => {
    // 42 пары разведки: 0 или больше одного кандидата ингредиента.
    const p = bunkerPeriod({
      залито: 500,
      возвращено: 100,
      норма: 400,
      чашек: 10,
      ingredientId: "какой-то-кандидат",
      тараОткалибрована: true,
      однозначна: false, размещениеПолно: true,
      чашекБезНормы: 0,
    });
    assert.equal(p.полнота, "позиция неоднозначна");
    assert.equal(p.ingredientId, null, "неоднозначный ингредиент не прокидывается в выдачу");
    assert.equal(p.разница, null);
  });

  it("однозначная позиция прокидывает ingredientId в выдачу без изменений", () => {
    const p = bunkerPeriod({
      залито: 780,
      возвращено: 250,
      норма: 500,
      чашек: 62,
      ingredientId: "кофе",
      тараОткалибрована: true,
      однозначна: true, размещениеПолно: true,
      чашекБезНормы: 0,
    });
    assert.equal(p.ingredientId, "кофе");
    assert.equal(p.полнота, "полный");
  });

  it("возврат равен заливке — нетто 0, это полный период (весь объём вернули), не «тара не откалибрована»", () => {
    const p = bunkerPeriod({ залито: 500, возвращено: 500, норма: 400, чашек: 10, тараОткалибрована: true, однозначна: true, размещениеПолно: true, чашекБезНормы: 0 });
    assert.equal(p.полнота, "полный");
    assert.equal(p.факт, 0);
    assert.equal(p.разница, -400);
  });

  it("не размещённая позиция приоритетнее «тара не откалибрована» — числовое противоречие не проверяется вовсе", () => {
    const p = bunkerPeriod({
      залито: 500,
      возвращено: 700,
      норма: 400,
      чашек: 10,
      тараОткалибрована: false,
      однозначна: true, размещениеПолно: true,
      чашекБезНормы: 0,
    });
    assert.equal(p.полнота, "нет тары");
  });

  it("machineId/position/from/to по умолчанию — пустая строка/0, если не заданы", () => {
    const p = bunkerPeriod({ залито: 780, возвращено: 250, норма: 500, чашек: 62, тараОткалибрована: true, однозначна: true, размещениеПолно: true, чашекБезНормы: 0 });
    assert.equal(p.machineId, "");
    assert.equal(p.position, 0);
    assert.equal(p.from, "");
    assert.equal(p.to, "");
  });

  it("ревью 1.1: хотя бы одна чашка без нормы — «рецепт неизвестен», а не заниженная разница", () => {
    // Норма частично посчиталась (200) — именно эта ситуация опасна: без
    // отдельной причины период выглядел бы «полным» с заниженной нормой и
    // перерасходом, которого нет (см. шапку файла).
    const p = bunkerPeriod({
      залито: 780,
      возвращено: 250,
      норма: 200,
      чашек: 12,
      чашекБезНормы: 5,
      тараОткалибрована: true,
      однозначна: true, размещениеПолно: true,
    });
    assert.equal(p.полнота, "рецепт неизвестен");
    assert.equal(p.разница, null, "разницы нет там, где часть нормы не посчиталась");
    assert.equal(p.чашекБезНормы, 5);
  });

  it("ревью 1.1: «рецепт неизвестен» проверяется раньше «нормы нет» — норма null не маскирует чашекБезНормы", () => {
    const p = bunkerPeriod({
      залито: 780,
      возвращено: 250,
      норма: null,
      чашек: 3,
      чашекБезНормы: 3,
      тараОткалибрована: true,
      однозначна: true, размещениеПолно: true,
    });
    assert.equal(p.полнота, "рецепт неизвестен", "все чашки без нормы — это точнее, чем общее «нормы нет»");
  });

  it("ревью 1.1: «позиция неоднозначна» приоритетнее «рецепт неизвестен» — ингредиент ещё не решён", () => {
    const p = bunkerPeriod({
      залито: 780,
      возвращено: 250,
      норма: null,
      чашек: 3,
      чашекБезНормы: 3,
      тараОткалибрована: true,
      однозначна: false, размещениеПолно: true,
    });
    assert.equal(p.полнота, "позиция неоднозначна");
  });

  it("ревью 1.1: чашекБезНормы: 0 не мешает «полный» — обычный случай не сломан", () => {
    const p = bunkerPeriod({ залито: 780, возвращено: 250, норма: 500, чашек: 62, чашекБезНормы: 0, тараОткалибрована: true, однозначна: true, размещениеПолно: true });
    assert.equal(p.полнота, "полный");
    assert.equal(p.разница, 30);
    assert.equal(p.чашекБезНормы, 0);
  });
});

describe("bunkerPeriod — размещение автомата (R-F2, блокер Б2)", () => {
  it("неполное размещение — вердикта нет, даже когда всё остальное в порядке", () => {
    // Числа те же, что в фикстуре «полный период» выше: единственное отличие
    // входа — размещение покрывает интервал не целиком.
    const p = bunkerPeriod({
      залито: 780,
      возвращено: 250,
      норма: 500,
      чашек: 62,
      чашекБезНормы: 0,
      тараОткалибрована: true,
      однозначна: true,
      размещениеПолно: false,
    });
    assert.equal(p.полнота, "размещение неполно");
    assert.equal(p.разница, null, "часть чашек интервала невидима — разница была бы обвинением на пустом месте");
    assert.equal(p.факт, 530, "сырой факт считается всегда, как и в остальных отброшенных состояниях");
  });

  it("проверяется РАНЬШЕ нормы: без размещения «нормы нет» не маскирует настоящую причину", () => {
    const p = bunkerPeriod({
      залито: 500,
      возвращено: 100,
      норма: null,
      чашек: 0,
      чашекБезНормы: 0,
      тараОткалибрована: true,
      однозначна: true,
      размещениеПолно: false,
    });
    assert.equal(p.полнота, "размещение неполно", "нормы нет ИМЕННО потому, что чашки выброшены — это и надо показать");
  });
});
