import { DAY } from "./expiry";

/**
 * Календарные сутки без времени и без зоны: `YYYY-MM-DD` ↔ номер суток от
 * эпохи.
 *
 * ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ КОПИЯ НА ФАЙЛ. Эти две строчки уже жили приватными
 * близнецами в двух местах — `dayNumber`/`isoOfDay` в `maintenance-due.ts` и
 * `dayToUtc`/`utcToDay` в `vending-reports.ts`. Копии такого рода расходятся
 * молча и ровно на единицу, а единица суток в графике обслуживания читается
 * как «просрочено на день», в границах недели — как чужой понедельник.
 *
 * ЭТО НЕ ЧАСОВОЙ ПОЯС. Здесь календарная арифметика над УЖЕ посчитанными
 * сутками. Свести момент к ташкентским суткам умеет `tashkentDay`, и второй
 * константы смещения в репозитории быть не должно (R-FW-11).
 *
 * Через номера суток, а не делением миллисекунд «как получится»: деление
 * ошибается на датах, где между полуночами не ровно 24 часа.
 */

/** `YYYY-MM-DD` → число суток от эпохи. Только дата, без времени и без зоны. */
export function dayNumber(iso: string): number {
  const [y, m, d] = iso.split("-").map(Number);
  return Math.floor(Date.UTC(y, m - 1, d) / DAY);
}

/** Число суток от эпохи → `YYYY-MM-DD`. */
export function isoOfDay(n: number): string {
  return new Date(n * DAY).toISOString().slice(0, 10);
}
