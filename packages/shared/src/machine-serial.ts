/**
 * Серийник автомата — приведение к общему виду для сопоставления с реестром.
 *
 * ЗАЧЕМ. Один и тот же снек-автомат приходит в MYDON в двух написаниях:
 *
 *   mydon-stock  → «C2508160376»  (форма из кабинета Ourvend, вписана руками)
 *   Ourvend API  → «2508160376»   (MuMachineID, как отдаёт вендор)
 *
 * В `entity.external_ref` трёх снековых карточек лежит первая форма, потому что
 * карточки заводили по данным mydon-stock. Конвейеры `sale` и `machine_stock`
 * сравнивают серийники точным равенством после `lower()` — и с этой формой
 * работают (676 строк привязаны). А новый Ourvend-коннектор присылает вторую
 * форму, и она не сходится ни с чем: слоты ложатся, но к автомату не крепятся.
 *
 * Канон по `docs/DATA_SOURCES.md` — форма БЕЗ буквы. Но менять значения в
 * реестре нельзя: это сломает уже работающую привязку продаж и остатков.
 * Поэтому чиним сопоставление, а не хранилище — обе формы дают один ключ.
 *
 * ПОЧЕМУ ПРАВИЛО ТАКОЕ УЗКОЕ. Срезать ведущую «c» безоглядно нельзя: коды
 * кофемашин шестнадцатеричные, и среди них есть `c7a6181f0000` — живой автомат,
 * которому такой срез сломал бы привязку. Отсюда два ограничения сразу:
 * после «c» должны идти ТОЛЬКО цифры и ровно столько, сколько их в серийнике
 * Ourvend. Код кофемашины — 12 символов, то есть «c» + 11; под правило он не
 * попадает даже в вырожденном случае, когда все 11 оказались цифрами.
 */

/** Длина серийника Ourvend: «2508160376» — ровно 10 цифр. */
const OURVEND_SERIAL_DIGITS = 10;

/** «c» + ровно 10 цифр и ничего больше. Всё остальное — не наш случай. */
const PREFIXED_OURVEND_SERIAL = new RegExp(`^c(\\d{${OURVEND_SERIAL_DIGITS}})$`);

/**
 * Серийник в канонической форме: без пробелов, в нижнем регистре, без ведущей
 * «c» у серийников Ourvend. Всё, что под правило не подошло, возвращается как
 * есть (только trim + lower) — коды кофемашин проходят насквозь.
 */
export function normalizeMachineSerial(raw: string | null | undefined): string {
  const s = (raw ?? "").trim().toLowerCase();
  const m = PREFIXED_OURVEND_SERIAL.exec(s);
  return m ? m[1]! : s;
}

/**
 * Ключи, под которыми автомат можно найти: исходное написание и каноническое.
 *
 * Нужны там, где строится карта «серийник → карточка»: класть обе формы значит
 * не потерять ни одно сопоставление, которое работает сегодня. Чистая замена на
 * канон была бы правкой поведения — а тут нужна добавка к нему.
 *
 * Пустая строка ключей не даёт: пустой `external_ref` не должен склеивать
 * между собой все карточки без внешнего кода.
 */
export function machineSerialKeys(raw: string | null | undefined): string[] {
  const s = (raw ?? "").trim().toLowerCase();
  if (s.length === 0) return [];
  const canonical = normalizeMachineSerial(s);
  return canonical === s ? [s] : [s, canonical];
}

/**
 * Два серийника — про один автомат? Сравнение по канону, а не по написанию.
 */
export function sameMachineSerial(a: string | null | undefined, b: string | null | undefined): boolean {
  const na = normalizeMachineSerial(a);
  const nb = normalizeMachineSerial(b);
  return na.length > 0 && na === nb;
}

/**
 * SQL-выражение того же правила — для запросов, где сопоставление идёт на
 * стороне базы (backfill привязки в `sale` и `machine_stock`).
 *
 * Держать правило в двух местах плохо, но альтернатива хуже: тянуть десятки
 * тысяч строк в приложение ради строкового сравнения. Regexp здесь дословно
 * повторяет `PREFIXED_OURVEND_SERIAL` — при правке менять оба места, о чём
 * напоминает тест `machine-serial.test.ts`.
 */
export const MACHINE_SERIAL_SQL_REGEX = `^c([0-9]{${OURVEND_SERIAL_DIGITS}})$`;

/** Кусок SQL: приведение колонки к каноническому виду. */
export function machineSerialSql(column: string): string {
  return `regexp_replace(lower(coalesce(${column}, '')), '${MACHINE_SERIAL_SQL_REGEX}', '\\1')`;
}
