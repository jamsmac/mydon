/**
 * Стандартные нормативы обслуживания — те самые «три числа», без которых
 * раздел «Графики» остаётся пустым по смыслу.
 *
 * Числа подтверждены владельцем 06.08.2026 из практики, а не из мануала
 * производителя (`docs/FIELD_OPS_SPEC.md` §9, вопрос 2 — закрыт):
 *
 *   мойка миксера    — 10 дней
 *   фильтр воды      — 45 дней
 *   плановое ТО      — 90 дней
 *
 * Почему это данные в коде, а не строки в базе: норматив одинаков для всего
 * парка и меняется решением владельца, а не эксплуатацией. Список нужен
 * ДО того, как в базе появится первый план, — им планы и заводятся
 * (`MaintenanceService.applyStandardNorms`). Отклонение по конкретному
 * автомату выражается правкой или выключением его плана, а не правкой этого
 * файла: план в базе всегда главнее.
 *
 * Периодичность задана в днях, а не в месяцах, потому что владелец назвал
 * дни. Разница не косметическая: `everyMonths` считает срок календарными
 * месяцами (31 марта → 30 апреля), `everyDays` — ровным шагом. Для ТО «раз в
 * 90 дней» ровный шаг и есть то, что имелось в виду.
 */

import type { MaintenanceKind, PartKind } from "./maintenance";

/**
 * Где норматив применим.
 *
 * `coffee` — только кофейные автоматы (привязанные к кофейной точке).
 * У снек-автомата нет ни миксера, ни фильтра воды, и график такой работы
 * на нём будет краснеть за работу, которой не существует. Ровно так парк
 * и превращается в красный экран, в который перестают смотреть.
 *
 * `any` — любой автомат. Плановое ТО осмысленно и для кофе, и для снека.
 */
export type NormScope = "coffee" | "any";

export interface MaintenanceNorm {
  kind: MaintenanceKind;
  /** Узел, если норматив про узел. null — про автомат целиком. */
  partKind: PartKind | null;
  everyDays: number;
  /** Название в графике и в задаче исполнителю. */
  title: string;
  scope: NormScope;
}

/**
 * Порядок значим: он же порядок строк при массовом заведении планов, а значит
 * и порядок, в котором владелец увидит их в панели. Сверху то, что чаще.
 *
 * `part_replace` у фильтра, а не `service`, выбран намеренно. Ключ норматива —
 * `(объект, вид работ, узел)`, и тот же ключ у факта в журнале: техник в боте
 * отмечает смену фильтра мастером «Замена детали» (`kind = part_replace`,
 * `part_kind = water_filter`). Заведи мы норматив как `service`, факт и план
 * встали бы в разные строки, и график требовал бы работу, которую только что
 * сделали.
 */
export const STANDARD_NORMS: readonly MaintenanceNorm[] = [
  { kind: "cleaning", partKind: "mixer", everyDays: 10, title: "Мойка миксера", scope: "coffee" },
  {
    kind: "part_replace",
    partKind: "water_filter",
    everyDays: 45,
    title: "Замена фильтра воды",
    scope: "coffee",
  },
  { kind: "service", partKind: null, everyDays: 90, title: "Плановое ТО", scope: "any" },
] as const;

/** Нормативы, применимые к объекту: кофейному — все, прочему — только общие. */
export function normsFor(isCoffee: boolean): readonly MaintenanceNorm[] {
  return isCoffee ? STANDARD_NORMS : STANDARD_NORMS.filter((n) => n.scope === "any");
}

/**
 * Ключ норматива — тот же, что уникальный индекс `maintenance_plan_key`:
 * объект + вид работ + узел, где отсутствующий узел это пустая строка.
 * `coalesce(part_kind, '')` в базе существует ровно потому, что NULL ≠ NULL,
 * и сравнение здесь обязано повторять поведение индекса — иначе повторный
 * прогон массового заведения упрётся в конфликт вместо «уже есть».
 */
export function normKey(entityId: string, kind: string, partKind?: string | null): string {
  return `${entityId}|${kind}|${partKind ?? ""}`;
}
