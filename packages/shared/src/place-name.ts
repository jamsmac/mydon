/**
 * Имя аппарата как указание на место.
 *
 * В хозяйстве владельца аппарат часто назван своей точкой: «American Hospital»,
 * «Parus F4», «Winners school». Когда на одной точке появился второй аппарат,
 * имена разошлись уточнителем: «American Hospital · снек» рядом с кофейным
 * «American Hospital». Точка при этом одна и та же.
 *
 * Поэтому для сопоставления берём ДВА ключа: имя целиком и имя без хвостового
 * уточнителя. Полное имя проверяется первым — если место названо ровно так,
 * рассуждать не о чем.
 */
import { normalizeSourceKey } from "./sources";

/** Разделитель уточнителя — только средняя точка в пробелах. */
const УТОЧНИТЕЛЬ = /\s·\s([^·]{1,16})$/;

/**
 * Ключи имени: полное и без уточнителя.
 *
 * Правило намеренно узкое, как и канон серийника. Режем только по средней точке
 * в пробелах и только короткий хвост — «Parus · F4» не тронем при длинном
 * хвосте, а дефис и скобки не трогаем вовсе: «Снек (без точки)» должен остаться
 * собой, иначе он совпал бы с чем угодно.
 *
 * Пустой или слишком короткий остаток отбрасываем: ключ «a» связал бы аппарат с
 * первой попавшейся точкой.
 */
export function placeNameKeys(name: string | null | undefined): string[] {
  const полное = normalizeSourceKey(name ?? "");
  if (полное.length === 0) return [];
  const m = УТОЧНИТЕЛЬ.exec(полное);
  if (m === null) return [полное];
  const основа = полное.slice(0, полное.length - m[0]!.length).trim();
  return основа.length >= 3 ? [полное, основа] : [полное];
}
