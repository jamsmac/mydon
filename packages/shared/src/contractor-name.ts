/**
 * Сопоставление имени поставщика с карточкой контрагента.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ МОДУЛЕМ. Поле «поставщик» на карточке сырья владелец
 * заполняет так, как произносит вслух: «AURATRADE 18», «ANGLESEY FOOD
 * (розница, корпоративная карта)». Карточка контрагента приходит из Didox с
 * полным юридическим написанием: `"AURATRADE 18" MCHJ`, `ANGLESEY FOOD MCHJ XK`,
 * `ООО "KMS ROASTING TRADING"`. Точное сравнение строк сходится ровно в одном
 * случае из восьми — поле выглядит заполненным, а ссылки нет, и владелец
 * решает, что связи не существует.
 *
 * ПОЧЕМУ НЕ ПО ИНН. Правильный ключ — ИНН, и когда он появится на карточке
 * сырья, сравнение по имени станет запасным путём. Сегодня ИНН на карточках
 * сырья нет, а связь нужна: без неё «поставщик» — мёртвая строка.
 *
 * ЧТО СОЗНАТЕЛЬНО НЕ ДЕЛАЕМ. Ни нечёткого сравнения, ни «похожести» по
 * расстоянию Левенштейна: два разных поставщика с близкими именами связались
 * бы молча и увели закупки не на ту карточку. Нормализуем только то, что
 * заведомо не несёт смысла различия — юридическую форму, кавычки и
 * пояснение в скобках, — и требуем после этого ТОЧНОГО равенства.
 */

/**
 * Юридические формы и их латинско-кириллические написания. Убираем только
 * их — не любые короткие слова: «18» в `AURATRADE 18` часть имени, а не форма.
 */
const LEGAL_FORMS = [
  "mchj",
  "xk",
  "qk",
  "ooo",
  "ооо",
  "llc",
  "ltd",
  "мчж",
  "хк",
  "оао",
  "зао",
  "аж",
  "aj",
  "чп",
  "ip",
  "yatt",
  "ятт",
];

/**
 * Имя в сравнимом виде: без пояснения в скобках, кавычек, юридической формы,
 * лишних пробелов и регистра. Пустая строка — сравнивать нечего.
 */
export function normalizeContractorName(raw: string | null | undefined): string {
  if (typeof raw !== "string") return "";
  // Пояснение в скобках — комментарий владельца («розница, корпоративная
  // карта»), а не часть имени.
  const withoutNote = raw.replace(/\([^)]*\)/g, " ");
  const withoutQuotes = withoutNote.replace(/[«»""'`"]/g, " ");
  const words = withoutQuotes
    .toLowerCase()
    .split(/[\s,.]+/)
    .filter((w) => w.length > 0 && !LEGAL_FORMS.includes(w));
  return words.join(" ");
}

/** Карточка контрагента в том минимуме, что нужен для сопоставления. */
export interface ContractorRef {
  id: string;
  name: string;
}

/**
 * Найти карточку контрагента по имени поставщика с карточки сырья.
 *
 * null — не нашли ИЛИ нашли больше одной: одноимённые карточки нельзя
 * разводить угадыванием, молча выбранная «первая подходящая» увела бы
 * историю закупок на чужого контрагента. Лучше честное «имя не совпало».
 */
export function matchContractorByName(
  supplier: string | null | undefined,
  contractors: readonly ContractorRef[],
): ContractorRef | null {
  const key = normalizeContractorName(supplier);
  if (key === "") return null;
  const hits = contractors.filter((c) => normalizeContractorName(c.name) === key);
  return hits.length === 1 ? hits[0]! : null;
}
