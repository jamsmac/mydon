import { tashkentDay, tashkentDayStart } from "./tashkent-time";

/**
 * Серия зелёных дней паритета OurVend — гейт катовера (R-P8b-1, R-P8b-2).
 *
 * Считает по журналу событий `ourvend.parity` (их пишет
 * `OurvendParityService.daily()` раз в сутки в 08:40), сколько дней подряд обе
 * половины сверки — продажи И остатки — сошлись. Взятый порог открывает
 * переключение `OURVEND_ACCOUNTING_SOURCE=own`, то есть решение, после
 * которого чужая база перестаёт быть источником учёта. Поэтому счёт живёт
 * здесь, чистой функцией под тестами, а не в SQL-выражении: числа, по которым
 * гасят донора, обязаны быть проверяемы без базы.
 *
 * ДВА РЕШЕНИЯ, КОТОРЫЕ НЕЛЬЗЯ «УПРОСТИТЬ».
 *
 * 1. ОТСУТСТВУЮЩИЙ СЕГОДНЯШНИЙ ДЕНЬ СЕРИЮ НЕ РВЁТ. Паритет считается кроном в
 *    08:40 по Ташкенту — до него сегодняшние сутки ЗАКОННО пусты. Считай мы
 *    пропуск сегодняшнего дня обрывом, счётчик обнулялся бы каждую полночь и
 *    показывал бы ноль всё утро, то есть был бы бесполезен ровно тогда, когда
 *    владелец на него смотрит. Курсор поэтому начинается с сегодняшнего дня и
 *    сдвигается на вчера, ЕСЛИ события за сегодня нет вовсе. Сдвиг ровно на
 *    одни сутки: он покрывает «крон ещё не отработал», а не «сверка молчит
 *    вторые сутки» — вторая дыра подряд серию обрывает.
 *
 * 2. СОБЫТИЕ СТАРОЙ ФОРМЫ — НЕ ЗЕЛЁНОЕ. До 26.08.2026 `daily()` писал вердикт
 *    ТОЛЬКО по продажам: ключей `остатки_*` в payload не было вовсе
 *    (единственное прод-событие 25.08 — как раз такое). Гейт же один: он
 *    открывает переключение источника и для `sale`, и для `machine_stock`.
 *    Зачесть половину проверки за целую значит открыть флип по половине
 *    гейта — поэтому день без чисел по остаткам красный, и `lastRed` честно
 *    показывает его дату.
 *
 * Ключи payload РУССКИЕ: так их пишет `daily()`, и переименовывать их здесь
 * («красивее») значило бы читать журнал не тем, чем он записан.
 */

/** Строка журнала `event` типа `ourvend.parity`: ключи payload РУССКИЕ (так их пишет daily()). */
export interface ParityEventRow {
  occurredAt: Date;
  payload: Record<string, unknown>;
}

/** Один день сверки — как его видит витрина. */
export interface ParityDay {
  /** Ташкентские сутки события, `YYYY-MM-DD`. */
  date: string;
  /** Зелёный по R-P8b-1: продажи И остатки, и остатков сверено хоть что-то. */
  ok: boolean;
  /** Сверенных пар ПРОДАЖ. 0 — сверять было нечего, а не «всё сошлось». */
  salesChecked: number;
  /** Сверенных пар ОСТАТКОВ. 0 — день не зелёный, чем бы ни был `ok`. */
  stockChecked: number;
  /** Записка вердикта («сверять не по чему») — без неё ноль читается как успех. */
  note: string | null;
}

export interface ParityStreak {
  /** Зелёных дней подряд до сегодняшнего (или вчерашнего, см. решение 1). */
  greenDays: number;
  /** Порог из настроек (`CUTOVER_GREEN_DAYS`) — тем же ответом, что и счёт. */
  threshold: number;
  readyForCutover: boolean;
  /** Последние 14 дней С СОБЫТИЕМ, свежие сверху. Пропущенные сутки строки не имеют. */
  days: ParityDay[];
  /** Дата последнего НЕзелёного дня. `null` — красных среди поданных событий не было. */
  lastRed: string | null;
  /** Первый день текущей серии, `null` — серии нет. Едет в payload `cutover_ready`. */
  since: string | null;
}

/**
 * Сколько дней показываем витрине — две недели.
 *
 * Окно ПОКАЗА, а не счёта: серия длиннее окна (после катовера её никто не
 * обнуляет) считается целиком, обрезается только список для глаз.
 */
export const PARITY_STREAK_WINDOW = 14;

const СУТКИ_МС = 86_400_000;

const число = (v: unknown): number => (typeof v === "number" && Number.isFinite(v) ? v : 0);

/**
 * Зелёный день (R-P8b-1): сошлись ОБЕ половины гейта и остатков сверено хоть
 * что-то.
 *
 * Проверяются ЧИСЛА, а не только флаг `ok`: «расхождений 0» при нуле
 * сравненных пар — это и есть тот самый ноль, который читается как «всё
 * хорошо» (прод: снимок остатков лежал только за сегодня, фильтр
 * `dt < current_date` выбрасывал его целиком, и половина гейта отчитывалась
 * «ok» ни о чём).
 */
function зелёный(p: Record<string, unknown>): boolean {
  return (
    p.ok === true &&
    typeof p.остатки_сверено === "number" &&
    p.остатки_сверено > 0 &&
    p.расхождений === 0 &&
    p.остатки_расхождений === 0
  );
}

/** Предыдущие ташкентские сутки. Смещение зоны — одно на репозиторий (`tashkent-time`). */
function предыдущийДень(date: string): string {
  const начало = tashkentDayStart(date);
  // `date` всегда приходит из `tashkentDay`, то есть уже голая дата; ветка —
  // страховка типа, а не сценарий.
  return начало ? tashkentDay(new Date(начало.getTime() - СУТКИ_МС)) : date;
}

/**
 * Серия зелёных дней по журналу событий паритета.
 *
 * `today` — ташкентская дата «сегодня», параметром: иначе «серия до
 * сегодняшнего дня» проверялась бы датой прогона тестов.
 *
 * Порядок входа не важен — сортируем сами. Полагаться на `order by`
 * вызывающего значило бы отдать правильность гейта на откуп чужому запросу;
 * тот же приём, что у `failedStreak` (`apps/core/src/vending/sync-streak.ts`).
 */
export function parityStreak(
  events: readonly ParityEventRow[],
  threshold: number,
  today: string,
): ParityStreak {
  // Несколько событий за одни сутки (ручной прогон `daily()` после починки) —
  // это УТОЧНЕНИЕ вердикта, а не второй день: берём самое позднее.
  const поДням = new Map<string, ParityEventRow>();
  for (const e of [...events].sort((a, b) => a.occurredAt.getTime() - b.occurredAt.getTime())) {
    поДням.set(tashkentDay(e.occurredAt), e);
  }

  const дни: ParityDay[] = [...поДням.entries()]
    .map(([date, e]) => ({
      date,
      ok: зелёный(e.payload),
      salesChecked: число(e.payload.сверено_пар),
      stockChecked: число(e.payload.остатки_сверено),
      note: typeof e.payload.примечание === "string" ? e.payload.примечание : null,
    }))
    .sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0));

  const зелёныеДни = new Map(дни.map((d) => [d.date, d.ok]));

  // Курсор — сегодня; сдвигается на вчера, только если события за сегодня нет
  // ВОВСЕ (см. решение 1 в шапке). Красный сегодняшний день обнуляет сразу.
  let курсор = зелёныеДни.has(today) ? today : предыдущийДень(today);
  let greenDays = 0;
  let since: string | null = null;
  while (зелёныеДни.get(курсор) === true) {
    greenDays += 1;
    since = курсор;
    курсор = предыдущийДень(курсор);
  }

  return {
    greenDays,
    threshold,
    readyForCutover: greenDays >= threshold,
    days: дни.slice(0, PARITY_STREAK_WINDOW),
    lastRed: дни.find((d) => !d.ok)?.date ?? null,
    since,
  };
}
