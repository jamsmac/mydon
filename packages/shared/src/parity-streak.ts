import { tashkentDay, tashkentDayStart } from "./tashkent-time";

/**
 * Серия зелёных дней паритета OurVend — гейт катовера (R-P8b-1, R-P8b-2).
 *
 * Считает по журналу событий `ourvend.parity` (их пишет
 * `OurvendParityService.daily()` раз в сутки в 08:40), сколько дней подряд обе
 * половины сверки — продажи И остатки — сошлись. Взятый порог открывает
 * переключение `OURVEND_ACCOUNTING_SOURCE=own`, то есть решение, после
 * которого чужая база перестаёт быть источником учёта. Поэтому счёт живёт
 * здесь, чистой функцией под тестами, а не в SQL-выражении: числа, по которым
 * гасят донора, обязаны быть проверяемы без базы.
 *
 * ТРИ РЕШЕНИЯ, КОТОРЫЕ НЕЛЬЗЯ «УПРОСТИТЬ».
 *
 * 1. ОТСУТСТВУЮЩИЙ СЕГОДНЯШНИЙ ДЕНЬ СЕРИЮ НЕ РВЁТ. Паритет считается кроном в
 *    08:40 по Ташкенту — до него сегодняшние сутки ЗАКОННО пусты. Считай мы
 *    пропуск сегодняшнего дня обрывом, счётчик обнулялся бы каждую полночь и
 *    показывал бы ноль всё утро, то есть был бы бесполезен ровно тогда, когда
 *    владелец на него смотрит. Курсор поэтому начинается с сегодняшнего дня и
 *    сдвигается на вчера, ЕСЛИ события за сегодня нет вовсе. Сдвиг ровно на
 *    одни сутки: он покрывает «крон ещё не отработал», а не «сверка молчит
 *    вторые сутки» — вторая дыра подряд серию обрывает.
 *
 * 2. ДЕНЬ СУДИТСЯ ПОЛЯМИ ДНЯ (`день_*`), А НЕ СЕМИДНЕВНОЙ ВИТРИНОЙ. `daily()`
 *    пишет в одном событии ДВЕ вещи: витрину за неделю (`сверено_пар`,
 *    `остатки_*`, «как сейчас выглядит вся сверка») и ВЕРДИКТ ЗА ОДИН
 *    ПОСЛЕДНИЙ ПОЛНЫЙ ДЕНЬ (`день_ok`, `день_продаж_сверено`,
 *    `день_остатков_сверено`, `день_расхождений` — из `parity(1)`). Серия
 *    считается ТОЛЬКО по вторым. Причина найдена на прод-данных: окно
 *    `parity(7)` берёт `dt >= current_date - 7`, то есть один грязный день
 *    входит в СЕМЬ последующих вердиктов подряд — одна продажа в
 *    пятнадцатиминутном разрыве между съёмами красила бы гейт неделю, и семь
 *    зелёных не наступили бы почти никогда (P ≈ 9 % на месяц). Грязный день
 *    обязан стоить одни сутки.
 *
 * 3. СОБЫТИЕ СТАРОЙ ФОРМЫ — НЕ ЗЕЛЁНОЕ. У событий до 26.08.2026 полей `день_*`
 *    нет вовсе (а у самых старых нет и `остатки_*`). Догадываться о вердикте
 *    дня по недельной витрине нельзя: она зелёная и в тот день, когда сам день
 *    был красным. Нет полей дня — день не зелёный, и `lastRed` честно
 *    показывает его дату.
 *
 * Ключи payload РУССКИЕ: так их пишет `daily()`, и переименовывать их здесь
 * («красивее») значило бы читать журнал не тем, чем он записан.
 */

/**
 * Строка журнала `event` типа `ourvend.parity`: ключи payload РУССКИЕ (так их
 * пишет `daily()`).
 *
 * Читаются отсюда ТОЛЬКО поля дня (`день_ok`, `день_продаж_сверено`,
 * `день_остатков_сверено`, `день_расхождений`, необязательное
 * `день_примечание`) — недельная витрина в том же payload серию не судит.
 */
export interface ParityEventRow {
  occurredAt: Date;
  payload: Record<string, unknown>;
}

/**
 * Один день сверки — как его видит витрина.
 *
 * ВСЕ ЧИСЛА ЗДЕСЬ — ЗА ЭТОТ ДЕНЬ (`день_*` из payload), а не за недельное окно
 * витрины. Иначе строка спорила бы сама с собой: вердикт `ok` — суточный, а
 * «сверено 14 пар» — недельное, и владелец читал бы красный день с числами
 * зелёной недели.
 */
export interface ParityDay {
  /** Ташкентские сутки события, `YYYY-MM-DD`. */
  date: string;
  /** Зелёный по R-P8b-1: вердикт ЗА ЭТОТ ДЕНЬ — продажи И остатки, и остатков сверено хоть что-то. */
  ok: boolean;
  /** Сверенных пар ПРОДАЖ за этот день. 0 — сверять было нечего, а не «всё сошлось». */
  salesChecked: number;
  /** Сверенных пар ОСТАТКОВ за этот день. 0 — день не зелёный, чем бы ни был `ok`. */
  stockChecked: number;
  /** Записка вердикта дня («сверять не по чему») — без неё ноль читается как успех. */
  note: string | null;
}

export interface ParityStreak {
  /** Зелёных дней подряд до сегодняшнего (или вчерашнего, см. решение 1). */
  greenDays: number;
  /**
   * Порог из настроек (`CUTOVER_GREEN_DAYS`) — тем же ответом, что и счёт.
   * Всегда ≥ 1 (см. пол в `parityStreak`), даже если на вход подали ноль.
   */
  threshold: number;
  readyForCutover: boolean;
  /** Последние 14 дней С СОБЫТИЕМ, свежие сверху. Пропущенные сутки строки не имеют. */
  days: ParityDay[];
  /**
   * Дата последнего НЕзелёного дня среди ВСЕХ поданных событий.
   * `null` — красных не было.
   *
   * МОЖЕТ ЛЕЖАТЬ ВНЕ `days`: окно показа — две недели, а «когда в последний раз
   * рвалось» ищется по всему прочитанному журналу. Витрине это надо подписать
   * («последний сбой N-го»), а не пытаться найти эту дату в списке строк —
   * при длинной серии её там не будет.
   */
  lastRed: string | null;
  /** Первый день текущей серии, `null` — серии нет. Едет в payload `cutover_ready`. */
  since: string | null;
}

/**
 * Сколько дней показываем витрине — две недели.
 *
 * Окно ПОКАЗА, а не счёта: серия длиннее окна (после катовера её никто не
 * обнуляет) считается целиком, обрезается только список для глаз.
 */
export const PARITY_STREAK_WINDOW = 14;

const СУТКИ_МС = 86_400_000;

const число = (v: unknown): number => (typeof v === "number" && Number.isFinite(v) ? v : 0);

/**
 * Зелёный день (R-P8b-1, уточнение P1b): сошлись ОБЕ половины гейта ЗА ЭТОТ
 * ДЕНЬ и остатков сверено хоть что-то.
 *
 * ЧИТАЮТСЯ ТОЛЬКО ПОЛЯ ДНЯ. Недельные `ok`/`расхождений`/`остатки_сверено`
 * рядом в том же payload — это витрина, и судить по ним значит растягивать
 * один грязный день на неделю вердиктов (см. решение 2 в шапке).
 *
 * Проверяются ЧИСЛА, а не только флаг `день_ok`: «расхождений 0» при нуле
 * сравненных пар — это и есть тот самый ноль, который читается как «всё
 * хорошо» (прод: снимок остатков лежал только за сегодня, фильтр
 * `dt < current_date` выбрасывал его целиком, и половина гейта отчитывалась
 * «ok» ни о чём). Проверка ТИПА (`typeof … === "number"`) — это же и отсев
 * событий старой формы: у них полей дня нет вовсе, и `undefined > 0` молча
 * дало бы `false`, а `undefined === 0` — красный день по правильной причине,
 * но случайно.
 */
function зелёный(p: Record<string, unknown>): boolean {
  return (
    p.день_ok === true &&
    typeof p.день_продаж_сверено === "number" &&
    typeof p.день_остатков_сверено === "number" &&
    p.день_остатков_сверено > 0 &&
    p.день_расхождений === 0
  );
}

/** Предыдущие ташкентские сутки. Смещение зоны — одно на репозиторий (`tashkent-time`). */
function предыдущийДень(date: string): string {
  const начало = tashkentDayStart(date);
  // `date` всегда приходит из `tashkentDay`, то есть уже голая дата; ветка —
  // страховка типа, а не сценарий.
  return начало ? tashkentDay(new Date(начало.getTime() - СУТКИ_МС)) : date;
}

/**
 * Серия зелёных дней по журналу событий паритета.
 *
 * `today` — ташкентская дата «сегодня», параметром: иначе «серия до
 * сегодняшнего дня» проверялась бы датой прогона тестов.
 *
 * Порядок входа не важен — сортируем сами. Полагаться на `order by`
 * вызывающего значило бы отдать правильность гейта на откуп чужому запросу;
 * тот же приём, что у `failedStreak` (`apps/core/src/vending/sync-streak.ts`).
 *
 * ПОЛ ПОРОГА В ОДИН ДЕНЬ — ЗДЕСЬ, А НЕ ТОЛЬКО У ВЫЗЫВАЮЩЕГО. Core свой порог
 * уже зажимает (`cutoverThreshold`), но функция экспортируется из
 * `@mydon/shared` наружу, и её числа рисуют «✅ можно переключать» в боте и
 * панели. Порог `0` (описка в настройке, чужой вызов) без пола означал бы
 * `0 >= 0` — разрешение на катовер при ПУСТОМ журнале, то есть гейт, снятый
 * опиской. Зажатый порог уезжает и в ответ (`threshold`), чтобы витрина,
 * которая сравнивает поля сама, сравнивала с тем же числом.
 */
export function parityStreak(
  events: readonly ParityEventRow[],
  threshold: number,
  today: string,
): ParityStreak {
  const порог = Math.max(1, Math.trunc(threshold) || 1);

  // Несколько событий за одни сутки (ручной прогон `daily()` после починки) —
  // это УТОЧНЕНИЕ вердикта, а не второй день: берём самое позднее.
  const поДням = new Map<string, ParityEventRow>();
  for (const e of [...events].sort((a, b) => a.occurredAt.getTime() - b.occurredAt.getTime())) {
    поДням.set(tashkentDay(e.occurredAt), e);
  }

  const дни: ParityDay[] = [...поДням.entries()]
    .map(([date, e]) => ({
      date,
      ok: зелёный(e.payload),
      salesChecked: число(e.payload.день_продаж_сверено),
      stockChecked: число(e.payload.день_остатков_сверено),
      // Записка ДНЯ, а недельная — только для событий старой формы, где поля
      // дня ещё не писались: показать в строке дня недельную записку («снимков
      // остатков нет») лучше, чем не показать ничего.
      note:
        typeof e.payload.день_примечание === "string"
          ? e.payload.день_примечание
          : typeof e.payload.примечание === "string"
            ? e.payload.примечание
            : null,
    }))
    .sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0));

  const зелёныеДни = new Map(дни.map((d) => [d.date, d.ok]));

  // Курсор — сегодня; сдвигается на вчера, только если события за сегодня нет
  // ВОВСЕ (см. решение 1 в шапке). Красный сегодняшний день обнуляет сразу.
  let курсор = зелёныеДни.has(today) ? today : предыдущийДень(today);
  let greenDays = 0;
  let since: string | null = null;
  while (зелёныеДни.get(курсор) === true) {
    greenDays += 1;
    since = курсор;
    курсор = предыдущийДень(курсор);
  }

  return {
    greenDays,
    threshold: порог,
    // `greenDays > 0` — страховка на случай, если пол порога когда-нибудь
    // подвинут: «готовы» при нулевой серии не бывает ни при каком пороге.
    readyForCutover: greenDays > 0 && greenDays >= порог,
    days: дни.slice(0, PARITY_STREAK_WINDOW),
    lastRed: дни.find((d) => !d.ok)?.date ?? null,
    since,
  };
}
