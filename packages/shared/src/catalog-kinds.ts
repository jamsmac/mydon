/**
 * Вид автомата и характер расхода товара — классификация, задаваемая при
 * заведении карточки (WAREHOUSE_SPEC §4.0).
 *
 * Живёт в общем пакете по той же причине, что и словарь обслуживания: одни
 * и те же значения пишет панель, читает бот и проверяет Core. Разъехавшись,
 * они дадут «snack» на одном экране и «снек» на другом, и владелец не поймёт,
 * одно это и то же или нет.
 *
 * Зачем поле вместо вывода из данных. До него «кофейный ли автомат»
 * определялось наличием привязки к кофейной точке. На боевом парке из 29
 * автоматов трое с кофейными серийниками привязки не имели — и попали
 * в «прочие» не потому, что они прочие, а потому что связь никто не завёл.
 * Косвенный признак заводится для одной цели, а используется для другой,
 * и в день, когда его забыли проставить, система молча ошибается.
 */

export const MACHINE_KINDS = ["coffee", "snack", "drink", "combo", "other"] as const;
export type MachineKind = (typeof MACHINE_KINDS)[number];

export const MACHINE_KIND_LABELS: Record<MachineKind, string> = {
  coffee: "Кофейный",
  snack: "Снек",
  drink: "Напитки",
  combo: "Снек + напитки",
  other: "Не размечен",
};

/**
 * `other` — это «не размечен», а не «прочий тип».
 *
 * Разница важна для экранов: автомат, которому вид не проставили, надо
 * показывать как незавершённую работу, а не как законный тип. Иначе список
 * «что осталось разметить» посчитать не из чего.
 */
export const isMachineKindSet = (k: string | null | undefined): boolean =>
  k !== null && k !== undefined && k !== "other" && (MACHINE_KINDS as readonly string[]).includes(k);

export const machineKindLabel = (k: string | null | undefined): string =>
  k ? (MACHINE_KIND_LABELS[k as MachineKind] ?? k) : "Не размечен";

