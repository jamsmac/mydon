/**
 * Состояние автомата — работает он сейчас или нет.
 *
 * Решение владельца 07.08.2026: заводим ЯВНЫЙ признак, а не выводим состояние
 * из привязки к точке.
 *
 * ЗАЧЕМ ЯВНЫЙ. Дешёвая альтернатива — правило «нет текущего размещения →
 * задач не ставим» — неверна в обе стороны. Автомат может стоять на точке и
 * быть сломанным: правило сочло бы его рабочим. И наоборот: аппарат на складе
 * действительно не привязан к точке, но молчит он не поэтому, а потому что не
 * работает. Правило дало бы верный ответ по неверной причине и развалилось бы
 * при первой поломке в поле.
 *
 * Это ровно та ошибка, на которой уже обожглись с видом автомата
 * (`catalog-kinds.ts`): «кофейный ли» выводили из привязки к кофейной точке,
 * и трое автоматов с кофейными серийниками попали в прочие только потому, что
 * связь никто не завёл. Косвенный признак заводится для одной цели, а
 * используется для другой — и в день, когда его забыли проставить, система
 * молча ошибается.
 *
 * ГРАНИЦЫ. Состояние отвечает на вопрос «работает ли аппарат», и только на
 * него. Оно НЕ заменяет:
 *   · `machine_card.kind`        — что это за автомат;
 *   · размещение                  — где он стоит;
 *   · `entity.approved_at`        — признан ли владельцем фактом;
 *   · `maintenance_plan.isActive` — нужен ли конкретный норматив.
 *
 * Последнее — единственное реальное пересечение. Разграничение: состояние
 * гасит работы по ВСЕМУ автомату и снимается вместе с возвратом в строй;
 * `isActive` гасит ОДИН норматив по отдельному решению («этот фильтр мы
 * больше не меняем»). При противоречии сильнее состояние: автомата нет на
 * месте, и выполнить работу физически невозможно, каким бы живым ни числился
 * норматив.
 */

export const MACHINE_STATUSES = ["in_service", "warehouse", "repair"] as const;
export type MachineStatus = (typeof MACHINE_STATUSES)[number];

export const MACHINE_STATUS_LABELS: Record<MachineStatus, string> = {
  in_service: "В эксплуатации",
  warehouse: "На складе",
  repair: "В ремонте",
};

/**
 * Значение по умолчанию.
 *
 * `in_service`, а не «неизвестно»: парк работает, и молчаливое исключение
 * автомата из обслуживания опаснее лишней задачи. Ошибка в сторону «работает»
 * даёт задачу, которую человек закроет одним касанием; ошибка в другую сторону
 * даёт тишину, которую никто не заметит, — а это ровно то, от чего признак и
 * заводится.
 */
export const DEFAULT_MACHINE_STATUS: MachineStatus = "in_service";

export const isMachineStatus = (s: string | null | undefined): s is MachineStatus =>
  s !== null && s !== undefined && (MACHINE_STATUSES as readonly string[]).includes(s);

export const machineStatusLabel = (s: string | null | undefined): string =>
  s ? (MACHINE_STATUS_LABELS[s as MachineStatus] ?? s) : MACHINE_STATUS_LABELS[DEFAULT_MACHINE_STATUS];

/**
 * Автомат в поле: работы по нему имеют смысл.
 *
 * Единственная функция, которую спрашивают все потребители — монитор графиков,
 * эмиссия задач, сводки. Одна точка решения вместо `status === "in_service"`,
 * рассыпанного по коду: когда появится четвёртое состояние (списан, продан),
 * его хватит добавить здесь.
 *
 * Пустое значение считается рабочим — см. `DEFAULT_MACHINE_STATUS`.
 */
export const machineIsOperational = (s: string | null | undefined): boolean =>
  (s ?? DEFAULT_MACHINE_STATUS) === "in_service";

/**
 * Почему автомат не в строю — строкой для человека.
 *
 * Нужна там, где задача НЕ ставится: молча пропустить работу нельзя, иначе
 * график выглядит выполненным. В журнале и в сводке должно быть написано, что
 * работа не назначена и по какой причине.
 */
export const machineIdleReason = (s: string | null | undefined): string | null =>
  machineIsOperational(s) ? null : `автомат не в эксплуатации (${machineStatusLabel(s).toLowerCase()})`;
