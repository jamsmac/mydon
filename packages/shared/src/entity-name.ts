/**
 * Имя карточки реестра: сколько это вообще может быть знаков.
 *
 * ЗАЧЕМ ГРАНИЦА. 04.08.2026 импорт книги владельца завёл две карточки, у
 * которых в поле `name` лежал целый кусок накладной: 1223 и 1246 знаков со
 * склейкой строк от РАЗНЫХ контрагентов сразу — EAST-WEST INVEST (ИНН
 * 302512057), NOVIY DOM TASHKENT (306018952) и ещё два ИНН. Парсер съехал по
 * строкам, а импортёр принял результат молча: имя он проверял только снизу
 * («не короче двух знаков»).
 *
 * Восстановить настоящее имя из такой склейки нельзя — в ней несколько
 * контрагентов, и какой из них принадлежит ключу карточки, из текста не
 * следует. Поэтому граница нужна не для красоты вывода: имя длиной в документ
 * означает, что разбор источника сломан, и принимать такую строку — значит
 * впечатать поломку в реестр навсегда.
 *
 * Значение общее с DTO панели: два предела разошлись бы при первой же правке.
 */
export const MAX_ENTITY_NAME = 512;

/**
 * Что не так с именем карточки. `null` — всё в порядке.
 *
 * Отдаём причину строкой, а не `false`: импортёр показывает её владельцу, и
 * «имя длиной 1223 знака» объясняет, что чинить, а «неверное имя» — нет.
 */
export function entityNameProblem(name: string | null | undefined): string | null {
  const s = (name ?? "").trim();
  if (s.length < 2) return "имя короче двух знаков";
  if (s.length > MAX_ENTITY_NAME) {
    return `имя длиной ${s.length} знаков — это не имя, а строка документа (предел ${MAX_ENTITY_NAME})`;
  }
  return null;
}

/**
 * Сколько карточек отдаёт выборка реестра по умолчанию и максимум.
 *
 * Предел был зашит числом прямо в запросе, и выборка обрезалась молча: в
 * реестре 1156 карточек, из них 704 счёта, а проверка реестра видела первые
 * 500 и печатала «расхождений не найдено». Усечение, о котором никто не знает,
 * читается как «всё чисто» — худший вид ответа.
 *
 * Значения общие для DTO и сервиса: разъехавшись, они дали бы отказ валидации
 * на числе, которое сервис принял бы спокойно.
 */
export const DEFAULT_FIND_LIMIT = 500;
export const MAX_FIND_LIMIT = 5000;
