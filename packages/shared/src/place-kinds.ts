/**
 * Вид места — где может стоять автомат.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ СЛОВАРЬ. Владелец 07.08.2026: «места ремонта могут быть
 * разные — как наш склад, так и мастерская; нужно называть их, отмечать на
 * карте и задавать вид». До этого мест в системе не было вовсе: кофейные
 * точки жили в своём справочнике `coffee_location`, а склад существовал
 * только как тип в коде складского учёта — ни одной записи на проде.
 *
 * ПОЧЕМУ ВИД — ЭТО `entity.type`, А НЕ ОТДЕЛЬНАЯ КАРТОЧКА. Соблазн повторить
 * приём `machine_card` (тонкая карточка с полем kind) велик, но здесь он
 * дороже и хуже. Складской учёт ищет склады по `entity.type = 'warehouse'` —
 * это 85 мест в коде: приход, перемещение, остатки, панель, бот. Введение
 * `place_card.kind` заставило бы переписать их все ради названия, которое уже
 * есть. Тип карточки в этом реестре И ЕСТЬ её вид: так живут `product`,
 * `contractor`, `invoice`.
 *
 * ЧТО ДАЁТСЯ ДАРОМ, раз место — карточка реестра:
 *   · координаты и карта — `geo_point` привязан к `entity`, миграции не нужно;
 *   · утверждение владельцем — `approved_at` уже есть у каждой карточки;
 *   · поиск, вложения, задачи по объекту — всё это про `entity`.
 */

export const PLACE_TYPES = ["location", "warehouse", "workshop"] as const;
export type PlaceType = (typeof PLACE_TYPES)[number];

export const PLACE_TYPE_LABELS: Record<PlaceType, string> = {
  location: "Точка продаж",
  warehouse: "Склад",
  workshop: "Мастерская",
};

/** Подсказка в форме: чем один вид отличается от другого. */
export const PLACE_TYPE_HINTS: Record<PlaceType, string> = {
  location: "Автомат стоит и продаёт. Сюда считается выручка.",
  warehouse: "Автомат хранится и не работает. Выручки нет по определению.",
  workshop: "Автомат в ремонте. Работы по графику ему не назначаются.",
};

export const isPlaceType = (t: string | null | undefined): t is PlaceType =>
  t !== null && t !== undefined && (PLACE_TYPES as readonly string[]).includes(t);

export const placeTypeLabel = (t: string | null | undefined): string =>
  t ? (PLACE_TYPE_LABELS[t as PlaceType] ?? t) : "Место";

/**
 * Место, где автомат ПРОДАЁТ.
 *
 * Отдельная функция, а не сравнение с `"location"` по коду: когда появится
 * четвёртый вид (павильон, витрина у партнёра), правило будет в одном месте.
 * Выручка, дефицит и планограмма имеют смысл только здесь — на складе и в
 * мастерской автомат не торгует.
 */
export const placeSells = (t: string | null | undefined): boolean => t === "location";

/**
 * Ключи координат в `attrs` карточки.
 *
 * Кириллические, потому что их вводит владелец руками в карточке и видит как
 * подписи полей (`geo.ts`: coordFromAttrs читает «широта»/«долгота»).
 * Вынесены сюда, чтобы карта-пикер и форма писали в одни и те же ключи, а не
 * в похожие.
 */
export const PLACE_ATTR = {
  lat: "широта",
  lng: "долгота",
  address: "адрес",
} as const;
