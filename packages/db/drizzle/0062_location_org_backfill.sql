-- Локации без организации невидимы в панели.
--
-- `entities.service.ts::find()` фильтрует `where org_id = <орг направления>`,
-- поэтому строка с `org_id IS NULL` не выпадает в ошибку — она просто НЕ
-- ПОПАДАЕТ в выдачу. Ни экран «Места», ни «Реестр» такую запись не покажут,
-- и отказ выглядит как «её не заводили».
--
-- Источник: разбор кофе-импорта (`approvals.service.ts`) заводил точки
-- строкой `insert ... values({ type: "location", name, createdFrom })` без
-- `org_id`. Само создание чинится в том же PR; эта миграция подбирает уже
-- созданные.
--
-- Область намеренно узкая: только точки, только без организации, только
-- заведённые кофе-импортом. Кофе-импорт принадлежит vendhub — других
-- направлений он не касается. Чужие NULL-строки, если они появятся по другой
-- причине, эта миграция не тронет: угадывать их принадлежность нельзя.
update entity
set org_id = (select id from org where code = 'vendhub')
where type = 'location'
  and org_id is null
  and created_from = 'coffee-import'
  and exists (select 1 from org where code = 'vendhub');
