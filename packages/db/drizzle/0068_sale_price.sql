-- vending_product.sale_price (П5b «Аналитика снек-контура», R-P5b-6):
-- ЭТАЛОН витрины — сколько владелец решил брать за товар.
--
-- Зачем колонка. Витринной цены нет ни в одной таблице: `sale` знает только
-- ФАКТ (`amount / qty`), а факт сам себе эталоном быть не может. Без второго
-- операнда отчёт «разрыв витрины» (price_gap) возвращал бы ноль строк не
-- потому, что расхождений нет, а потому что сравнивать не с чем, — и это
-- худший вид пустого отчёта: он выглядит как «всё в порядке».
--
-- Почему CHECK (> 0), а не NOT NULL. Эталон появляется ПО ОДНОМУ товару —
-- бутстрапом по факту 14 суток или командой владельца; NOT NULL потребовал бы
-- выдумать цену всем 34 SKU разом. NULL здесь — честное «эталон не задан», и
-- отчёт показывает такие товары отдельным списком, а не нулевой строкой.
-- Ноль и отрицательное — не значение владельца, а мусор: цена 0 молча
-- превратила бы разрыв витрины в −100 % и увела бы «упущено» в минус.
-- CHECK стоит только здесь, в SQL, а не в drizzle-схеме — как у
-- `fixed_purchase_qty`/`pack_size` в 0066: `check()` в схеме заставил бы
-- генератор выпустить лишнюю миграцию ради уже поставленного ограничения.
--
-- Бэкфилла нет: заполнение — дело писателей (`POST /vending/sale-price` и
-- `/vending/sale-price/bootstrap`), а не миграции.
--
-- Файл написан руками по защитному паттерну 0066/0067: IF NOT EXISTS и
-- ограничение через DO $$ … EXCEPTION WHEN duplicate_object. Автодеплой
-- применяет миграции без отката — упавший оператор вешает выкатку молча и
-- навсегда, поэтому каждый оператор обязан быть безопасен на повторном
-- прогоне. Снапшот 0068 снят генератором с текущей schema.ts, так что
-- следующий db:generate снова честен.

ALTER TABLE "vending_product" ADD COLUMN IF NOT EXISTS "sale_price" numeric(12, 2);--> statement-breakpoint

DO $$ BEGIN
  ALTER TABLE "vending_product" ADD CONSTRAINT "vending_product_sale_price_positive" CHECK ("sale_price" > 0);
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
