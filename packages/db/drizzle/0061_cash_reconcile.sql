-- Купюры на инкассации + кассовый символ на движении денег (слой К: касса/инкассация).
-- Готовит поля для сверки набора купюр и для нал.-безнал. учёта взносов в банк.
--
-- Обе колонки — ADD COLUMN IF NOT EXISTS, без NOT NULL и без дефолта:
-- в collection 386 живых строк, в money_flow тоже есть данные, и обратной
-- совместимости здесь важнее, чем строгость на новых колонках.
--
-- collection.denominations — разбивка суммы по купюрам. Появляется только при
-- приёме и только если её вводили; из 386 живых инкассаций у 266 исторических
-- записей разбивки нет и не будет — это законно, а не пробел в данных.
--
-- money_flow.cash_symbol — кассовый символ банка, признак вида операции.
-- Взносы наличной выручки помечаются `0200`. Пусто у операций, которым банк
-- символ не присваивает (безнал, ручные записи и т.д.) — тоже законно.
--
-- Файл написан руками (как 0049–0060) по защитному паттерну 0059/0060:
-- ADD COLUMN IF NOT EXISTS, никаких новых ограничений на живые таблицы.
-- Автодеплой применяет миграции без отката — упавший оператор вешает выкатку
-- молча и навсегда, поэтому оба оператора ниже обязаны быть безопасны на
-- повторном прогоне и на живых данных. Снапшот 0061 снят с текущей
-- schema.ts, так что следующий db:generate снова честен.

ALTER TABLE "collection" ADD COLUMN IF NOT EXISTS "denominations" jsonb;--> statement-breakpoint
ALTER TABLE "money_flow" ADD COLUMN IF NOT EXISTS "cash_symbol" text;
