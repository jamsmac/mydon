#!/usr/bin/env node
/**
 * Проверка реестра: что в данных расходится само с собой.
 *
 * ЗАЧЕМ. 07–09.08.2026 расхождения находились по одному, каждое новым запросом
 * руками — и каждое успевало навредить, прежде чем его замечали:
 *
 *   · у аппарата поле «точка» указывало на прежнюю точку, и автопривязка
 *     увозила его туда, откуда он уехал ещё в мае;
 *   · миграция 0049 скопировала месту адрес и координаты у аппарата, который
 *     там уже не стоял, — у «Winners School» адресом стало имя ДРУГОЙ точки;
 *   · импорт книги завёл карточку, у которой в имени лежала склейка строк
 *     накладной от нескольких контрагентов сразу;
 *   · один адрес у двух аппаратов делал автосопоставление чужих выгрузок
 *     неоднозначным, а оно правит деньгами.
 *
 * Ни одно из этого не ломает работу заметно. Оно тихо врёт — и всплывает,
 * когда владелец смотрит на цифру и не понимает, откуда она.
 *
 * ЧТО ДЕЛАЕТ. Только читает. Ничего не чинит и не предлагает чинить
 * автоматически: у половины находок правильное значение знает лишь владелец.
 * Задача — назвать расхождение поимённо и сказать, чем оно грозит.
 *
 * Запуск НА СЕРВЕРЕ:
 *   cd /opt/mydon-app
 *   docker compose -f deploy/docker-compose.yml --env-file .env \
 *     exec -T mydon-core node tools/check-registry.mjs
 *
 * Код возврата 1, если нашлось хоть что-то, — чтобы годился для cron с
 * уведомлением. `--quiet` печатает только находки.
 */
const CORE = process.env.CORE_API_URL ?? "http://127.0.0.1:3001";
const TOKEN = process.env.SERVICE_TOKEN ?? "";
const QUIET = process.argv.includes("--quiet");

async function get(path) {
  const res = await fetch(`${CORE}${path}`, { headers: { "x-service-token": TOKEN } });
  if (!res.ok) throw new Error(`GET ${path} → ${res.status}: ${(await res.text()).slice(0, 300)}`);
  return res.json();
}

/** Свести написание к сравнимому виду — как это делает Core при сопоставлении. */
const ключ = (s) =>
  String(s ?? "")
    .replace(/[  ]/g, " ")
    .trim()
    .replace(/\s+/g, " ")
    .toLowerCase()
    .replace(/ё/g, "е");

/** Последняя точка из поля «история точек»: «A (с 01.01.2025) → B (с 02.02.2026)». */
function последняяВИстории(история) {
  if (typeof история !== "string" || история.length === 0) return null;
  const части = история.split("→");
  const хвост = части[части.length - 1] ?? "";
  const имя = хвост.split("(с ")[0]?.trim() ?? "";
  const дата = хвост.split("(с ")[1]?.split(")")[0]?.trim() ?? null;
  return имя.length > 0 ? { имя, дата } : null;
}

const находки = [];
const добавить = (важность, заголовок, строки, чем_грозит) => {
  if (строки.length > 0) находки.push({ важность, заголовок, строки, чем_грозит });
};

async function main() {
  const [машины, размещения] = await Promise.all([
    get("/entities?domain=vendhub&type=machine"),
    get("/coffee/placements"),
  ]);
  const места = [];
  for (const вид of ["location", "warehouse", "workshop"]) {
    места.push(...(await get(`/entities?domain=vendhub&type=${вид}`)));
  }

  const открытые = размещения.filter((p) => p.endDate === null);
  const стоит = new Map(открытые.map((p) => [p.entityId, p]));

  // 1. Аппарат без места: неизвестно, где он физически.
  добавить(
    "внимание",
    "Аппараты без места",
    машины.filter((m) => !стоит.has(m.id)).map((m) => `${m.name}${m.externalRef ? ` · ${m.externalRef}` : ""}`),
    "неизвестно, где стоит: не попадёт ни на карту, ни в отчёт по точке",
  );

  // 2. Поле «точка» расходится с «историей точек» ТОЙ ЖЕ карточки.
  //    Именно это увезло «Winners school» на точку, покинутую в мае.
  добавить(
    "важно",
    "Поле «точка» спорит с историей той же карточки",
    машины
      .map((m) => {
        const посл = последняяВИстории(m.attrs?.["история точек"]);
        const точка = m.attrs?.["точка"];
        if (!посл || typeof точка !== "string") return null;
        return ключ(точка) === ключ(посл.имя)
          ? null
          : `${m.name}: поле «${точка}», история «${посл.имя}»${посл.дата ? ` (с ${посл.дата})` : ""}`;
      })
      .filter(Boolean),
    "поле старше истории — по нему аппарат может уехать туда, откуда его давно забрали",
  );

  // 3. Один адрес у нескольких аппаратов: автосопоставление выгрузок молчит.
  const поТочке = new Map();
  for (const m of машины) {
    const т = m.attrs?.["точка"];
    if (typeof т !== "string" || т.trim().length === 0) continue;
    поТочке.set(ключ(т), [...(поТочке.get(ключ(т)) ?? []), m.name]);
  }
  добавить(
    "к сведению",
    "Один адрес у нескольких аппаратов",
    [...поТочке.entries()].filter(([, л]) => л.length > 1).map(([k, л]) => `«${k}»: ${л.join(" + ")}`),
    "автосопоставление выгрузок по такому адресу НЕ подсказывает — разберите вручную один раз",
  );

  // 4. Адрес места называет ДРУГОЕ место. След миграции 0049: адрес попал
  //    месту от аппарата, который там уже не стоял.
  const именаМест = new Set(места.map((p) => ключ(p.name)));
  добавить(
    "важно",
    "У места записан адрес другого места",
    места
      .filter((p) => p.geo?.address && ключ(p.geo.address) !== ключ(p.name) && именаМест.has(ключ(p.geo.address)))
      .map((p) => `${p.name}: адрес «${p.geo.address}» — так называется другое место`),
    "адрес и координаты указывают не туда: карта и отчёты покажут чужое место",
  );

  // 5. Размещение без даты начала: «стоит здесь, с какого числа — неизвестно».
  const безДаты = открытые.filter((p) => !p.startDate);
  const восстановимо = безДаты.filter((p) => {
    const м = машины.find((x) => x.id === p.entityId);
    const посл = последняяВИстории(м?.attrs?.["история точек"]);
    return посл && посл.дата && ключ(посл.имя) === ключ(p.locationName);
  });
  добавить(
    "к сведению",
    "Размещения без даты начала",
    безДаты.map((p) => `${p.machineName} на «${p.locationName}»`),
    `не видно, с какого числа аппарат там стоит; из «истории точек» восстановимо ${восстановимо.length} из ${безДаты.length}`,
  );

  // 6. Период нулевой длины — след качелей автопривязки: приехал и уехал в
  //    один день. Настоящих таких переездов не бывает.
  добавить(
    "важно",
    "Периоды нулевой длины",
    размещения
      .filter((p) => p.startDate && p.endDate && p.startDate === p.endDate)
      .map((p) => `${p.machineName} на «${p.locationName}» ${p.startDate}`),
    "аппарат не приезжает и не уезжает в один день — это след ошибочной перестановки",
  );

  // 7. Имя карточки длиной в документ (импорт до защиты MAX_ENTITY_NAME).
  //
  // Смотрим ВЕСЬ реестр, а не только VendHub: склейку строк накладной завёл
  // импорт книги владельца, и обе испорченные карточки — контрагент и счёт —
  // лежат в GLOBERENT. Проверка, ограниченная одним направлением, их не видела.
  // limit=5000 — реестр больше умолчания (1156 карточек, из них 704 счёта).
  // Если вернулось ровно столько, сколько просили, значит упёрлись в предел и
  // проверили НЕ ВСЁ: об этом надо сказать, а не промолчать.
  const ПРЕДЕЛ = 5000;
  const всеКарточки = await get(`/entities?limit=${ПРЕДЕЛ}`);
  if (всеКарточки.length >= ПРЕДЕЛ) {
    добавить(
      "важно",
      "Проверены не все карточки",
      [`выборка упёрлась в предел ${ПРЕДЕЛ} — часть реестра не просмотрена`],
      "остальные находки этого отчёта неполны",
    );
  }
  добавить(
    "к сведению",
    "Имя карточки длиной в документ",
    всеКарточки
      .filter((e) => (e.name ?? "").length > 512)
      .map((e) => `${e.type} ${e.externalRef ?? "—"}: ${e.name.slice(0, 55)}… (${e.name.length} знаков)`),
    "настоящее имя из такой склейки не восстановить — нужен владелец или повторный импорт",
  );

  // ── Вывод ───────────────────────────────────────────────────────────────
  if (!QUIET) {
    console.log(
      `Проверено: автоматов ${машины.length}, мест ${места.length}, размещений ${размещения.length},` +
        ` карточек всего ${всеКарточки.length}.`,
    );
    console.log("");
  }
  if (находки.length === 0) {
    console.log("Расхождений не найдено.");
    return 0;
  }
  const порядок = { важно: 0, внимание: 1, "к сведению": 2 };
  находки.sort((a, b) => порядок[a.важность] - порядок[b.важность]);
  for (const н of находки) {
    console.log(`[${н.важность}] ${н.заголовок} — ${н.строки.length}`);
    console.log(`  чем грозит: ${н.чем_грозит}`);
    for (const с of н.строки.slice(0, 12)) console.log(`    · ${с}`);
    if (н.строки.length > 12) console.log(`    … и ещё ${н.строки.length - 12}`);
    console.log("");
  }
  return 1;
}

main().then(
  (код) => process.exit(код),
  (e) => {
    console.error("проверка не отработала:", e.message);
    process.exit(2);
  },
);
