/**
 * Подключение к БД донора (mydon-stock) — ОДНО на всех читателей.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ. К чужой базе ходят трое: синк продаж
 * (`sales.service`), синк снабжения (`supply.service`) и — после флипа —
 * сверка паритета (`ourvend-parity.service`, R-FW-P3). Пока каждый открывал
 * подключение сам, параметры («не держать пул», таймаут, `prepare: false`
 * ради pgbouncer у донора) жили тремя копиями, и четвёртая копия в паритете
 * означала бы, что сверка ходит к донору не на тех условиях, на которых к
 * нему ходит учёт.
 *
 * ЧИТАТЕЛЬ ТОЛЬКО ЧИТАЕТ. Пользователь донора — read-only (правило проекта:
 * «Ничего не удалять в проектах-донорах»), и ни один вызывающий не шлёт сюда
 * ничего, кроме `select`. Строка подключения в логи не попадает НИКОГДА — в
 * них пишется только факт её наличия.
 *
 * Подключение короткоживущее и закрывается вызывающим в `finally`: чужая база
 * не должна держать наш пул, а наш процесс — её соединения.
 */

/** Параметры подключения к донору. `max: 1` — одно соединение на прогон, не пул. */
export const STOCK_DB_OPTIONS = { prepare: false, max: 1, connect_timeout: 10 } as const;

/** Открыть короткоживущее подключение к БД донора. Закрывать обязан вызывающий. */
export async function openStockDb(url: string) {
  const { default: postgres } = await import("postgres");
  return postgres(url, STOCK_DB_OPTIONS);
}

/** Тип открытого подключения — выводится из самой фабрики, чтобы не разойтись с ней. */
export type StockDb = Awaited<ReturnType<typeof openStockDb>>;
