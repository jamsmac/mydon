import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { ReportCache, зажать, перечислить } from "./report-cache";

describe("Кеш отчётов вендинга: один расчёт на ключ", () => {
  it("второй запрос того же ключа расчёт не запускает, другой ключ — запускает", async () => {
    const кеш = new ReportCache();
    let расчётов = 0;
    const считать = async () => {
      расчётов += 1;
      return расчётов;
    };

    assert.equal(await кеш.get("a", считать), 1);
    assert.equal(await кеш.get("a", считать), 1);
    assert.equal(расчётов, 1);
    assert.equal(await кеш.get("b", считать), 2);
  });

  it("параллельные запросы одного ключа ждут ОДИН расчёт", async () => {
    const кеш = new ReportCache();
    let расчётов = 0;
    // Очередь, а не одна переменная: `let x: (() => void) | null` TS сузил бы
    // до `null` — присваивание внутри колбэка для анализа потока невидимо.
    const очередь: (() => void)[] = [];
    const считать = async () => {
      расчётов += 1;
      await new Promise<void>((resolve) => очередь.push(resolve));
      return расчётов;
    };

    const оба = Promise.all([кеш.get("a", считать), кеш.get("a", считать)]);
    await Promise.resolve();
    for (const отпустить of очередь.splice(0)) отпустить();
    assert.deepEqual(await оба, [1, 1]);
    assert.equal(расчётов, 1);
  });

  it("нулевой TTL: кеш не отдаёт ничего — срок жизни считается по настенным часам", async () => {
    // TTL по ПЕРЕДАННОМУ моменту вместо настенных часов был бы незаметен здесь,
    // но убивал бы недельную сводку: у неё `now` зафиксирован границей недели и
    // не двигается никогда — запись не протухала бы до перезапуска процесса.
    const кеш = new ReportCache(0);
    let расчётов = 0;
    const считать = async () => (расчётов += 1);

    await кеш.get("a", считать);
    await кеш.get("a", считать);
    assert.equal(расчётов, 2);
  });

  it("clear() во время расчёта: результат старых данных в кеш не попадает", async () => {
    const кеш = new ReportCache();
    let расчётов = 0;
    const очередь: (() => void)[] = [];
    const медленно = async () => {
      расчётов += 1;
      await new Promise<void>((resolve) => очередь.push(resolve));
      return `версия-${расчётов}`;
    };

    const первый = кеш.get("a", медленно);
    await Promise.resolve();
    // Владелец правит цену ровно в этот момент: расчёт, который уже читает
    // базу, посчитан по старым данным и права лечь в кеш на пять минут не имеет.
    кеш.clear();
    очередь.shift()?.();
    assert.equal(await первый, "версия-1", "своему вызывающему расчёт ответ всё-таки отдаёт");

    const второй = кеш.get("a", медленно);
    await Promise.resolve();
    очередь.shift()?.();
    assert.equal(await второй, "версия-2", "после сброса отчёт обязан посчитаться заново");
  });

  it("протухшие записи выселяются на записи — карта не растёт вечно", async () => {
    const кеш = new ReportCache(0);
    await кеш.get("вчера|30", async () => 1);
    await кеш.get("сегодня|30", async () => 2);

    assert.equal(кеш.size, 1, "ключи чужих суток обязаны уходить, а не копиться");
  });
});

describe("Кеш отчётов: общие мелочи витрин", () => {
  it("зажать: мусор и ноль дают дефолт, слишком большое — потолок", () => {
    assert.equal(зажать(Number.NaN, 30, 90), 30);
    assert.equal(зажать(0, 30, 90), 30);
    assert.equal(зажать(-5, 30, 90), 30);
    assert.equal(зажать(45.9, 30, 90), 45);
    assert.equal(зажать(5000, 30, 90), 90);
  });

  it("перечислить: пять имён целиком, дальше — числом", () => {
    assert.equal(перечислить(["а", "б"]), "а, б");
    assert.equal(перечислить(["а", "б", "в", "г", "д"]), "а, б, в, г, д");
    assert.equal(перечислить(["а", "б", "в", "г", "д", "е", "ж"]), "а, б, в, г, д и ещё 2");
  });
});
