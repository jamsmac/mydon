import { REPORT_CACHE_MS } from "./shrinkage.service";

/**
 * Кеш готового отчёта плюс ОДИН расчёт на ключ (single-flight).
 *
 * Роуты отчётов открыты на чтение, а расчёт тяжёлый: продажи окна в память,
 * снимки остатков, лента событий. Без single-flight пять параллельных запросов
 * одного ключа запускали бы пять одинаковых расчётов — а кеш заполнялся бы
 * только после того, как все пятеро дошли до конца.
 *
 * `now` — параметр, а не `Date.now()` внутри: отчёты считаются на переданный
 * момент (прогон через полночь Ташкента иначе брал бы для окна одни сутки, а
 * для срока годности кеша другие), и тесты обязаны уметь двигать время.
 *
 * Ключ ВСЕГДА обязан включать ташкентские сутки расчёта: после полуночи окно
 * сдвигается, и вчерашний отчёт под тем же именем был бы уже не тем отчётом.
 * Проверить это здесь нельзя — ключ строит вызывающий, — поэтому напоминание
 * стоит в этом комментарии, а не в коде.
 */
export class ReportCache {
  private readonly готовые = new Map<string, { at: number; отчёт: unknown }>();
  private readonly вПолёте = new Map<string, Promise<unknown>>();

  constructor(private readonly ttlMs: number = REPORT_CACHE_MS) {}

  async get<T>(ключ: string, now: Date, расчёт: () => Promise<T>): Promise<T> {
    const готовое = this.готовые.get(ключ);
    if (готовое && now.getTime() - готовое.at < this.ttlMs) return готовое.отчёт as T;

    const считается = this.вПолёте.get(ключ);
    if (считается) return считается as Promise<T>;

    const работа = расчёт();
    this.вПолёте.set(ключ, работа);
    try {
      const отчёт = await работа;
      this.готовые.set(ключ, { at: now.getTime(), отчёт });
      return отчёт;
    } finally {
      this.вПолёте.delete(ключ);
    }
  }

  /** Сбросить всё: зовётся оттуда, где данные заведомо поменялись. */
  clear(): void {
    this.готовые.clear();
  }
}
