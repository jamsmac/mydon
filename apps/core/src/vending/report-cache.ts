/**
 * Общая механика витрин отчётов вендинга: кеш с одним расчётом на ключ и две
 * мелочи, которые до этого жили копиями в каждом отчёте (`зажать`,
 * `перечислить`).
 *
 * Копий было три — усушка, аналитика, недельная сводка, — и это ровно тот
 * случай, когда копии расходятся молча: у одной TTL считается по переданному
 * моменту, у другой по настенным часам, и владелец видит два разных ответа на
 * один вопрос в зависимости от того, какой отчёт он открыл первым.
 */

/**
 * Время жизни готового отчёта.
 *
 * Отчёты считаются по ЗАКРЫТЫМ суткам: внутри дня они меняются только от
 * догона продаж, поэтому пять минут — не устаревание, а окно склейки повторов.
 * Без кеша один открытый GET (`?days=60` — полмиллиона строк снимков) укладывал
 * Core, а вкладка «Снек» дёргает отчёты при каждом рендере.
 */
export const REPORT_CACHE_MS = 5 * 60_000;

/**
 * Кеш готового отчёта плюс ОДИН расчёт на ключ (single-flight).
 *
 * Роуты отчётов открыты на чтение, а расчёт тяжёлый: продажи окна в память,
 * снимки остатков, лента событий. Без single-flight пять параллельных запросов
 * одного ключа запускали бы пять одинаковых расчётов — а кеш заполнялся бы
 * только после того, как все пятеро дошли до конца.
 *
 * СРОК ЖИЗНИ СЧИТАЕТСЯ ПО НАСТЕННЫМ ЧАСАМ, а не по моменту отчёта. Момент
 * отчёта у вызывающего бывает ЗАФИКСИРОВАННЫМ: недельная сводка считает
 * прошлую неделю на её же границе, и `now` там не двигается никогда. Считай мы
 * TTL по нему, запись не протухала бы вовсе — правка данных не попала бы в
 * сводку до перезапуска процесса.
 *
 * Ключ ВСЕГДА обязан включать ташкентские сутки расчёта: после полуночи окно
 * сдвигается, и вчерашний отчёт под тем же именем был бы уже не тем отчётом.
 * Проверить это здесь нельзя — ключ строит вызывающий, — поэтому напоминание
 * стоит в этом комментарии, а не в коде.
 */
export class ReportCache {
  private readonly готовые = new Map<string, { at: number; отчёт: unknown }>();
  private readonly вПолёте = new Map<string, Promise<unknown>>();
  /**
   * Поколение кеша. Растёт на каждом `clear()` и решает судьбу расчётов,
   * которые стартовали ДО сброса: их результат посчитан по старым данным, и
   * класть его в кеш нельзя — иначе правка цены гасилась бы на пять минут
   * расчётом, который она же и обогнала. Своему вызывающему такой расчёт
   * ответ всё-таки отдаёт: он спрашивал раньше, чем данные поменялись.
   */
  private поколение = 0;

  constructor(private readonly ttlMs: number = REPORT_CACHE_MS) {}

  async get<T>(ключ: string, расчёт: () => Promise<T>): Promise<T> {
    const сейчас = Date.now();
    const готовое = this.готовые.get(ключ);
    if (готовое && сейчас - готовое.at < this.ttlMs) return готовое.отчёт as T;

    const считается = this.вПолёте.get(ключ);
    if (считается) return считается as Promise<T>;

    const поколение = this.поколение;
    const работа = расчёт();
    this.вПолёте.set(ключ, работа);
    try {
      const отчёт = await работа;
      if (поколение === this.поколение) {
        this.выселить();
        this.готовые.set(ключ, { at: Date.now(), отчёт });
      }
      return отчёт;
    } finally {
      // Только СВОЮ запись: после `clear()` по этому ключу уже может считаться
      // следующий расчёт, и удалить его значило бы снять single-flight.
      if (this.вПолёте.get(ключ) === работа) this.вПолёте.delete(ключ);
    }
  }

  /**
   * Сбросить всё: зовётся оттуда, где данные заведомо поменялись (правка цены,
   * приёмка накладной). Считающееся сейчас тоже теряет право попасть в кеш —
   * см. `поколение`.
   */
  clear(): void {
    this.готовые.clear();
    this.вПолёте.clear();
    this.поколение += 1;
  }

  /** Сколько готовых отчётов лежит в кеше — для диагностики и тестов выселения. */
  get size(): number {
    return this.готовые.size;
  }

  /**
   * Выселение протухших записей на КАЖДОЙ записи.
   *
   * Ключ отчёта содержит ташкентские сутки и окно, поэтому за месяц работы в
   * карте накопились бы все окна всех суток: сами по себе записи маленькие, но
   * расти они не переставали бы никогда. Проход по карте здесь дешевле любого
   * таймера: записей единицы, а зовётся он раз в пять минут на ключ.
   */
  private выселить(): void {
    // Условие — ТОЧНОЕ отрицание условия чтения (`сейчас - at < ttl`): иначе
    // запись, которую чтение уже считает протухшей, оставалась бы в карте
    // навсегда, и «выселение» не выселяло бы ничего при нулевом TTL.
    const порог = Date.now() - this.ttlMs;
    for (const [ключ, запись] of this.готовые) {
      if (запись.at <= порог) this.готовые.delete(ключ);
    }
  }
}

/**
 * Окно отчёта в границах: не число / не положительное — дефолт, слишком
 * большое — потолок.
 *
 * Молча зажимать МЕНЬШЕ запрошенного законно только сверху: владелец, попросив
 * 500 суток, получает максимум окна и видит его в поле `days` ответа.
 */
export function зажать(days: number, дефолт: number, потолок: number): number {
  const n = Math.trunc(days);
  if (!Number.isFinite(n) || n <= 0) return дефолт;
  return Math.min(n, потолок);
}

/** Сколько имён/дат называем поимённо; остальное числом — строка на полсотни нечитаема. */
export const МАКС_В_СТРОКЕ = 5;

/** «A, B, C и ещё 7» — общий вид перечисления в предупреждениях отчётов. */
export function перечислить(значения: readonly string[]): string {
  if (значения.length <= МАКС_В_СТРОКЕ) return значения.join(", ");
  return `${значения.slice(0, МАКС_В_СТРОКЕ).join(", ")} и ещё ${значения.length - МАКС_В_СТРОКЕ}`;
}
