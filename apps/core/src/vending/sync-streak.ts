/**
 * Серия отказов сбора OurVend — один расчёт на два места (R-P5b-8).
 *
 * Считают её двое: `/ourvend/health` (показать владельцу) и `finishSyncRun`
 * (решить, будить ли немедленно). Две реализации одного счёта неизбежно
 * разошлись бы — отчёт показывал бы 12, а тревога молчала бы на 2.
 *
 * ДВА РЕШЕНИЯ, КОТОРЫЕ НЕЛЬЗЯ «УПРОСТИТЬ».
 *
 * 1. `running` СЕРИЮ НЕ РВЁТ. Прогон, который прямо сейчас идёт (или завис без
 *    `finished_at`), ничего не говорит об итоге. Считать его успехом значило бы
 *    гасить тревогу ровно в тот момент, когда сбор запустился и снова падает;
 *    считать отказом — обвинять невиновного. Он пропускается.
 * 2. `partial` СЕРИЮ РВЁТ. Частичный сбор — это данные, которые приехали:
 *    «12 отказов подряд» после него было бы неправдой.
 *
 * `since` — момент старта САМОГО СТАРОГО прогона серии: владельцу нужно «с
 * какого часа мы слепые», а не «когда упало в последний раз».
 */

/**
 * С какого отказа подряд будим владельца немедленно (R-P5b-8).
 *
 * Один упавший прогон — обычное дело (сеть, таймаут кабинета), и тревога на
 * нём научила бы владельца не читать тревоги. Третий подряд — это уже сутки
 * потерянных продаж и остатков, которые задним числом не восстановить.
 */
export const FAILED_STREAK_ALERT = 3;

/**
 * Сколько прогонов читаем ради счёта серии — независимо от того, сколько
 * показываем. Серия длиннее показанного окна обычна (на проде их было 12 при
 * 10 строках в панели), и счёт по обрезанному списку занижал бы тревогу ровно
 * в тяжёлом случае.
 */
export const STREAK_SCAN_LIMIT = 200;

export interface SyncRunFacts {
  status: "running" | "success" | "partial" | "failed";
  startedAt: Date;
  error?: string | null;
}

export interface FailedStreak {
  /** Сколько ЗАВЕРШЁННЫХ прогонов подряд упало, считая от самого свежего. */
  streak: number;
  /** Старт первого прогона серии, ISO. `null` — серии нет. */
  since: string | null;
  /** Ошибка самого свежего отказа. `null` — серии нет или ошибку не записали. */
  lastError: string | null;
}

/**
 * Порядок входа не важен: сортируем сами. Полагаться на `order by` вызывающего
 * значило бы отдать правильность счёта на откуп двум разным запросам.
 */
export function failedStreak(runs: readonly SyncRunFacts[]): FailedStreak {
  const свежиеСверху = [...runs].sort((a, b) => b.startedAt.getTime() - a.startedAt.getTime());

  let streak = 0;
  let since: string | null = null;
  let lastError: string | null = null;
  for (const run of свежиеСверху) {
    if (run.status === "running") continue;
    if (run.status !== "failed") break;
    if (streak === 0) lastError = run.error ?? null;
    streak += 1;
    since = run.startedAt.toISOString();
  }
  return { streak, since, lastError };
}
