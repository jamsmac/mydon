import type { AnalyticsWarning, AnalyticsWarningCode } from "../lib/core";

/**
 * Хвост отчёта «Посчитано не всё» — `warnings` от Core (П5b), один в один
 * с ботом (`предупреждения()` в `apps/bot/src/analytics-brief.ts`).
 *
 * Это факты, которых в самих числах не видно: продажи автомата вне парка не
 * вошли в маржу, у автомата не нашлось остатка, себестоимость части штук
 * неизвестна. Молчание о них делает отчёт красивее и лживее — итог выглядит
 * полным, хотя часть данных до него не доехала.
 *
 * `covered` — коды, которые лист УЖЕ сказал своей строкой (например, маржа
 * сама печатает «N шт без себестоимости»). Читать одно и то же дважды —
 * сначала в теле отчёта, потом в хвосте — владелец не должен; ровно ради
 * этого у предупреждения есть код, а не только текст.
 *
 * Повторы по тексту гасим, как усушка (`shrinkage-view.tsx`): одна причина
 * приходит по каждому автомату, и три десятка одинаковых строк вытеснили бы
 * сам отчёт.
 */
export function ReportWarnings({
  warnings,
  covered = [],
}: {
  warnings?: AnalyticsWarning[];
  covered?: AnalyticsWarningCode[];
}) {
  const строки = [
    ...new Set((warnings ?? []).filter((w) => !covered.includes(w.code)).map((w) => w.message)),
  ];
  // Пустой заголовок «Посчитано не всё» без единой причины читался бы как
  // «что-то не посчитали, а что — не скажем».
  if (строки.length === 0) return null;
  return (
    <>
      <p className="hint">Посчитано не всё</p>
      {строки.map((m) => (
        <p className="muted" key={m}>{`⚠️ ${m}`}</p>
      ))}
    </>
  );
}

