import type { Entity } from "./core";

export type MachineKind = "coffee" | "snack" | "unknown";

/**
 * Цвета по виду техники — единые для схемы и настоящей карты.
 *
 * Значения, а не токены: их читает Leaflet и canvas, где CSS-переменные не
 * применимы. Подобраны под светлый холст `#f4f4ee`, все читаются на нём как
 * заливка с тёмной обводкой. Умышленно НЕ совпадают ни с брендом, ни с
 * тревогой: вид техники — это классификация, а не состояние, и путать её с
 * «нажми» нельзя.
 *
 * Сами точки карты — места (`place-points.ts`, М-4): прежние точки из
 * координат автомата сняты вместе с картой автоматов в волне 2.
 */
export const KIND_COLOR: Record<MachineKind, string> = {
  coffee: "#275e58",
  snack: "#627719",
  unknown: "#8b9689",
};

/**
 * Вид автомата — только из заполненного поля «категория» (10 — кофе).
 * Пустая категория = «не указан», а не «снеки»: выдавать незаполненное за
 * факт нельзя (находка ревизии 2026-07-30).
 */
export function machineKindOf(m: Entity): MachineKind {
  const raw = (m.attrs ?? {})["категория"];
  if (raw === undefined || raw === null || raw === "") return "unknown";
  return Number(raw) === 10 ? "coffee" : "snack";
}
