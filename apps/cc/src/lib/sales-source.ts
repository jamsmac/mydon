/**
 * Почему в журнале продаж нет цифр — ПО ДЕЙСТВУЮЩЕМУ ИСТОЧНИКУ УЧЁТА
 * (M2 финального ревью П8b).
 *
 * `configured` в `/sales/summary` означает «источник ЧИТАЕМ», а не «зеркало
 * настроено»: в режиме `stock` это заданный `STOCK_DATABASE_URL`, в режиме
 * `own` — свежий учётный снапшот. Один флаг, два разных отказа — и совет
 * «настрой `STOCK_DATABASE_URL`» после шага 3 рунбука катовера отправляет
 * владельца заводить переменную, которую он этим шагом только что УДАЛИЛ.
 * Чинить в режиме `own` надо агента `ourvend:accounting`, и сказать надо это.
 *
 * Тексты живут здесь, а не в трёх серверных компонентах: `sales-view` и
 * `reports-overview` — асинхронные серверные компоненты, их строки иначе
 * проверялись бы только глазами, а разъехавшись, объяснили бы одну и ту же
 * тишину двумя разными причинами.
 *
 * `source` НЕОБЯЗАТЕЛЬНЫЙ: Core прошлой сборки поля не шлёт, и «неизвестно»
 * здесь — это `stock`, каким режим и был.
 */
export type AccountingSource = "stock" | "own";

/** Пустой журнал: что именно чинить. */
export function причинаБезПродаж(source?: AccountingSource): string {
  return source === "own"
    ? "Учёт ведёт агент ourvend:accounting — снапшота за сутки нет."
    : "Синк продаж не настроен на сервере (STOCK_DATABASE_URL).";
}

/** Чип карточки «Журнал продаж»: короткий вердикт источника. */
export function чипИсточникаПродаж(configured: boolean, source?: AccountingSource): string {
  if (configured) return "источник настроен";
  return source === "own" ? "снапшот не пришёл" : "не настроен";
}
