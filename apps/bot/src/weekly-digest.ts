/**
 * Часть строки динамики: процент, а если сравнивать не с чем — абсолютный рост.
 *
 * Прошлая неделя в нуле даёт `pct === null` (см. `weekCompare`): «+100 %» там
 * было бы выдумкой, поэтому печатаем прибавку в единицах и говорим, что
 * сравнивать было не с чем.
 */
function часть(label: string, abs: number, pct: number | null, unit: string): string {
  if (pct !== null) return `${label} ${ЗНАК(pct)}`;
  if (abs === 0) return `${label} без изменений`;
  // Про пустую базу говорит ОДНА фраза — у ссылки на прошлую неделю (см.
  // `динамика`). Здесь её повтор давал «прошлая неделя» дважды подряд в одной
  // строке, а на трёх частях — трижды.
  return `${label} ${abs > 0 ? "+" : "−"}${RU(Math.abs(abs))}${unit}`;
}

/** Строка динамики к прошлой неделе. `null` — сравнивать не с чем вовсе. */
function динамика(d: WeekDelta, previousWeek: string): string | null {
  const пусто = d.qty === 0 && d.revenue === 0 && d.margin === 0;
  if (пусто && d.revenuePct === null) return null;
  // Процента нет — значит прошлая неделя была в нуле (см. `weekCompare`): это
  // свойство БАЗЫ, и сказать о нём надо там, где база названа.
  const база = d.revenuePct === null ? `${previousWeek}, была в нуле` : previousWeek;
  return [
    `${часть("Выручка:", d.revenue, d.revenuePct, " сум")} к прошлой неделе (${база})`,
    часть("маржа", d.margin, d.marginPct, " сум"),
    часть("штуки", d.qty, d.qtyPct, " шт"),
  ].join(" · ");
}

/** Одна строка автомата недели: деньги, маржа, штуки. */
function машина(m: WeeklyDigest["machines"][number]): string {
  return `• ${m.name}: выручка ${сум(m.revenue)} · маржа ${сум(m.margin)} (${PCT(m.pct)}) · ${RU(m.qty)} шт`;
}

/** «2026-08-06» → «06.08.2026». Год обязателен: неделя из `?week=` бывает годовой давности. */
function сутки(iso: string): string {
  return `${день(iso)}.${iso.slice(0, 4)}`;
}

/**
 * Строка прогонов сбора ЗА НЕДЕЛЮ: итог, четыре разряда и оговорки хвостом.
 *
 * Отдельной функцией, а не веткой внутри блока: у строки четыре состояния
 * (журнала ещё не было / пусто / посчитано / посчитано с оговоркой), и в
 * списке строк они читались бы вложенными тернарниками.
 *
 * ОБРЕЗКА ЖУРНАЛА (`capped`) хвостом НЕ печатается: та же причина едет в
 * `warnings` письма и уже печатается блоком «Посчитано не всё» — вместе с
 * адресом, где журнал виден целиком, которого в короткой пометке не было.
 * Одну причину владелец читает один раз (D4).
 */
function прогоныНедели(w: WeeklyHealth, конецНедели: string): string {
  // Оговорки идут ХВОСТОМ той же строки, а не отдельной: «неделя ещё идёт» под
  // числами читалось бы как новость о сборе, а не как их граница.
  const пометки = [...(w.partialWeek ? ["неделя ещё идёт"] : [])];
  const хвост = пометки.length === 0 ? "" : ` (${пометки.join("; ")})`;
  // НЕДЕЛЯ РАНЬШЕ ЖУРНАЛА — не «сбор не запускался». `?week=` пускает на 104
  // недели назад, а журнал `vending_sync_run` начат 06.08.2026: всё, что
  // раньше, честно отдаёт `runs: 0`. Прочитать это как аварию значило бы
  // отправить владельца искать поломку, которой не было. Ту же правду ядро
  // шлёт кодом `journal_short`; хвост письма её не повторяет
  // (`покрытоЗдоровьем`).
  const начало = журналНеДостаёт(w, конецНедели);
  if (начало !== null) {
    return `За неделю прогонов нет: журнал прогонов начинается с ${сутки(начало)} — за эту неделю данных нет`;
  }
  // Пустая неделя — не «отказов 0»: нули читаются как посчитанный результат, а
  // сбор чаще всего просто не запускался.
  if (w.runs === 0) return `За неделю прогонов не было — сбор не запускался${хвост}`;
  // Четыре разряда и итог печатаются ВМЕСТЕ и обязаны сходиться: `runs` в Core
  // считается их суммой ровно ради этой строки. «Незакрытых» — зависший прогон
  // без `finished_at`; для прошлой недели это сигнал сам по себе.
  return (
    `За неделю: прогонов ${RU(w.runs)} · успешных ${RU(w.success)} · частичных ${RU(w.partial)} · ` +
    `отказов ${RU(w.failed)} · незакрытых ${RU(w.running)} · худшая серия ${RU(w.worstFailedStreak)}${хвост}`
  );
}

/**
 * Здоровье сбора в сводке: ЧИСЛА НЕДЕЛИ, потом состояние момента (R-H-9).
 *
 * Раньше блок печатал только «сейчас», хотя письмо подписано неделей (дефект
 * O7): авария понедельничного утра попадала в письмо о ПРОШЛОЙ неделе, а
 * неделя, на которой сбор стоял двое суток, выглядела чистой, если к утру он
 * ожил. Теперь в блоке два набора чисел, и каждый подписан своим.
 *
 * Все строки момента — общие форматтеры «сверки» (`analytics-brief.ts`), а не
 * их пересказ. Своя формулировка разошлась бы с отчётом ровно там, где это
 * дороже всего: пустой журнал прогонов при `failedStreak: 0` читался бы как
 * «✅ отказов нет», хотя сбор просто ни разу не запускался, — а пустая неделя
 * чаще всего именно этим и объясняется. Застой сбора (`строкаЗастоя`,
 * R-P8a-6) — тот же общий форматтер и та же причина: две формулировки одного
 * и того же сигнала разошлись бы ровно там, где владелец меньше всего этого
 * ждёт — в письме, которое приходит само, без запроса.
 */
function здоровье(d: WeeklyDigest): string[] {
  const h = d.health;
  const застой = строкаЗастоя(h);
  const снапшот = строкаСнапшота(h);
  return [
    "",
    "🩺 Здоровье сбора OurVend",
    // ЧИСЛА НЕДЕЛИ ПЕРВЫМИ: письмо подписано неделей, и первым в блоке обязано
    // стоять то, о чём подпись.
    ...числаНедели(d),
    // Дальше — СОСТОЯНИЕ МОМЕНТА, подписанное словом «сейчас». Строки застоя и
    // снапшота не меняются вовсе: это те же общие форматтеры, что печатает
    // «сверка», и вторая формулировка одного сигнала разошлась бы там, где
    // владелец меньше всего этого ждёт — в письме, которое приходит само.
    ...(застой ? [`Сейчас: ${застой}`] : []),
    // Снапшот — сразу за застоем сбора, той же логикой, что и в «сверке»
    // (R-P8b-5): обе строки про одно «данные не едут».
    ...(снапшот ? [`Сейчас: ${снапшот}`] : []),
    `Сейчас: ${состояниеСбора(h)} · последний успех ${момент(h.lastSuccessAt)}`,
    // `прогоныСтрока(h.runs)` здесь БОЛЬШЕ НЕ ПЕЧАТАЕТСЯ (UX-6). Она считает
    // последние 20 прогонов — не неделю и не момент, — а подписи окна у неё
    // нет: «Прогоны (1): успешных 1 · частичных 0 · с отказом 0» стояла почти
    // той же лексикой в двух строках от «За неделю: прогонов 56 · успешных
    // 54 · частичных 1 · отказов 1». С телефона (а письмо читают именно так)
    // два таких блока читаются как противоречие отчёта самому себе. Счёт
    // недели даёт строка выше, состояние момента — строка «Сейчас: …»; третий
    // почти-дубль в ПИСЬМЕ лишний. В «сверке» строка остаётся как была: там
    // она единственная и окно у неё названо самой командой.
    свежестьСтрока(h),
    паритетСтрока(h.parity),
    // Серия — сразу после паритета, той же логикой, что и в «сверке» (R-P8b-2).
    строкаСерии(h),
  ];
}

/**
 * Числа НЕДЕЛИ письма — или честная строка о том, что их нет.
 *
 * `weekHealth` — новое ОБЯЗАТЕЛЬНОЕ поле ответа, а `request<WeeklyDigest>` —
 * непроверенный каст: форму с провода никто не валидирует. Старый Core (окно
 * перезапуска compose, откат образа при живом боте) отдал бы сводку без него,
 * `w.runs` бросил бы TypeError, `withRetries` повторил бы трижды на том же
 * месте — и понедельничное письмо не ушло бы вовсе, а следующее только через
 * неделю. Деньги недели при этом честные, и молчать о них из-за одной секции
 * нельзя: секция говорит, что её нет, письмо уходит.
 */
function числаНедели(d: WeeklyDigest): string[] {
  const w: WeeklyHealth | undefined = d.weekHealth;
  if (w === undefined) return ["За неделю: здоровье недели недоступно — числа ниже только про момент"];
  return [
    прогоныНедели(w, d.to),
    // Дней паритета за неделю может не быть вовсе (неделя глубже окна счёта
    // серии) — тогда строки нет, а причина названа в `warnings` письма:
    // «0 зелёных / 0 красных» читалось бы как посчитанный результат.
    //
    // Прилагательное склоняется тем же `сущ()`, что и у соседа `строкаСерии`:
    // неделя с одним зелёным днём после починки — рядовой случай, и «1
    // зелёных» встало бы в одном письме рядом с правильным «1 зелёный дн.».
    ...(w.parityDays.length === 0
      ? []
      : [
          `Паритет недели: ${RU(w.parityGreen)} ${сущ(w.parityGreen, "зелёный", "зелёных", "зелёных")} / ` +
            `${RU(w.parityRed)} ${сущ(w.parityRed, "красный", "красных", "красных")}`,
        ]),
    // Момент последних ДАННЫХ, а не «успеха»: правило Core — `success` ИЛИ
    // `partial`, и слово «успех» здесь спорило бы с разрядом «успешных N»
    // строкой выше. При нуле прогонов строка не нужна вовсе — о ней уже всё
    // сказано.
    ...(w.runs === 0
      ? []
      : [
          w.lastDataAt === null
            ? "Данные за неделю не приезжали ни разу — все прогоны без данных"
            : `Данные последний раз приехали: ${момент(w.lastDataAt)}`,
        ]),
  ];
}

/** Раздел изменений цен: свежие сверху, хвост назван числом, а не отброшен молча. */
function цены(title: string, rows: WeeklyDigest["priceChanges"]["purchase"], lines: string[]): void {
  if (rows.length === 0) return;
  lines.push(`${title} (${rows.length}):`);
  for (const c of rows.slice(0, CHANGES_SHOWN)) lines.push(изменениеСтрока(c));
  if (rows.length > CHANGES_SHOWN) {
    lines.push(`…и ещё ${rows.length - CHANGES_SHOWN} — весь список на листе «Цены» в панели.`);
  }
}

/** Тело сводки без сигналов правил: разделы в порядке R-P5b-7. */
function разделы(d: WeeklyDigest): string[] {
  const lines: string[] = [];
  const t = d.totals;

  // Пустая неделя — это НЕ «выручка ноль»: чаще всего стоит сбор. Нули
  // прочитались бы как посчитанный результат (R-P5b-7, §7 спеки).
  if (d.machines.length === 0 || t.revenue === 0) {
    lines.push("Считать нечего — продаж за неделю нет.");
  } else {
    lines.push(
      `Итого: выручка ${сум(t.revenue)} · маржа ${сум(t.margin)} (${PCT(t.pct)}) · ${RU(t.qty)} шт`,
    );
    if (t.unknownUnits > 0) {
      lines.push(`⚠️ ${RU(t.unknownUnits)} шт без себестоимости — на их выручку маржа завышена`);
    }
  }

  const δ = динамика(d.delta, d.previousWeek);
  if (δ) lines.push(δ);

  if (d.machines.length > 0) {
    lines.push("", "🎰 Автоматы:");
    for (const m of d.machines) lines.push(машина(m));
  }

  if (d.topProducts.length > 0) {
    lines.push("", `🏆 Лучшие по марже (${d.topProducts.length}):`);
    for (const p of d.topProducts) lines.push(товарСтрока(p));
  }
  if (d.worstProducts.length > 0) {
    lines.push("", `🔻 Худшие по марже (${d.worstProducts.length}):`);
    for (const p of d.worstProducts) lines.push(товарСтрока(p));
  }

  lines.push("", "📦 Работа за неделю:");
  const r = d.refills;
  if (r.events === 0) {
    lines.push("Заливок за неделю не было.");
  } else {
    // Снимки OurVend и запись мастера — два независимых источника. Разошлись
    // — говорим об этом: молчаливая разница и есть та дыра, из-за которой
    // усушка потом «появляется ниоткуда».
    const разрыв = r.detectedUnits !== r.recordedUnits ? " ⚠️ записано не всё" : "";
    lines.push(
      `Заливки: ${RU(r.events)} ${сущ(r.events, "событие", "события", "событий")}, ` +
        `${RU(r.detectedUnits)} ед по снимкам (записано ${RU(r.recordedUnits)})${разрыв}`,
    );
  }
  const i = d.intake;
  lines.push(
    i.orders === 0
      ? "Приходов за неделю не было."
      : `Приходы: ${RU(i.orders)} ${сущ(i.orders, "накладная", "накладные", "накладных")}, ` +
        `${RU(i.units)} ед на ${сум(i.amount)}`,
  );
  const s = d.stocktakes;
  lines.push(
    s.positions === 0
      ? "Инвентаризаций склада за неделю не было."
      : `Инвентаризации склада: ${RU(s.positions)} поз., последняя ${момент(s.lastCountedAt)}`,
  );

  if (d.deadStock.rows.length > 0) {
    lines.push("", `🪦 Мёртвый сток — всего ≈ ${сум(d.deadStock.totalValue)}, дороже прочих:`);
    for (const row of d.deadStock.rows.slice(0, DEAD_SHOWN)) lines.push(мёртваяСтрока(row));
    if (d.deadStock.rows.length > DEAD_SHOWN) {
      lines.push(
        `…и ещё ${RU(d.deadStock.rows.length - DEAD_SHOWN)} поз. — «мёртвый сток» покажет целиком.`,
      );
    }
  }

  const p = d.priceChanges;
  if (p.purchase.length > 0 || p.retail.length > 0) {
    lines.push("", "📈 Цены за неделю:");
    // Заголовки короче, чем в отчёте «цены»: там пояснение в скобках нужно
    // (отчёт спрашивают редко), здесь оно съедало бы строку каждую неделю.
    цены("🛒 Закупочные", p.purchase, lines);
    цены("🏷 Витринные", p.retail, lines);
  }

  lines.push(...здоровье(d));
  // Секция могла деградировать (Core ловит её падение и пишет причину в
  // `warnings`): молчаливая дыра в письме читается как «данных нет».
  lines.push(...предупреждения(d.warnings, покрытоЗдоровьем(d)));
  return lines;
}

/**
 * Коды, которые блок здоровья УЖЕ сказал СВОЕЙ строкой, — тем же приёмом, что
 * `ПОКРЫТО_МАРЖОЙ` и соседи: одну причину владелец читает один раз (D4).
 *
 * `journal_short` попадает сюда, только если строка про начало журнала
 * действительно напечатана. Гасить его безусловно нельзя: письмо без
 * `weekHealth` (старый Core) блок недели не печатает вовсе — тогда
 * предупреждение ядра остаётся единственным носителем этого факта.
 */
function покрытоЗдоровьем(d: WeeklyDigest): AnalyticsWarningCode[] {
  return журналНеДостаёт(d.weekHealth, d.to) === null ? [] : ["journal_short"];
}

/**
 * Неделя целиком раньше первого прогона в журнале → его начало, иначе `null`.
 *
 * ОДНО правило на два решения — что печатает блок и что гасится в хвосте:
 * вторая копия условия разошлась бы с первой ровно там, где это даёт либо
 * двойную строку, либо потерянный сигнал.
 *
 * `journalSince` читается через `typeof`, а не по `!== null`: у старого Core
 * поля в ответе нет вовсе, а форму с провода никто не валидирует.
 */
function журналНеДостаёт(w: WeeklyHealth | undefined, конецНедели: string): string | null {
  if (w === undefined || w.runs !== 0) return null;
  const начало = w.journalSince;
  return typeof начало === "string" && конецНедели < начало ? начало : null;
}

/**
 * Сводка недели плюс подмешанные сигналы правил `urgency:"weekly"`.
 *
 * Сигналы идут ПОСЛЕДНИМИ и с бюджетом на остаток: если сводка всё-таки не
 * влезла в `WEEKLY_MAX_PARTS`, срезается именно их хвост — и тогда ключи не
 * возвращаются вовсе (правило 2 в шапке: отметить недоставленное = потерять
 * его навсегда).
 */
export function formatWeeklyDigest(d: WeeklyDigest, notes: readonly BriefingNote[]): WeeklyMessage {
  const title = `📅 Итоги недели ${день(d.from)} — ${день(d.to)} · снек-автоматы (OurVend)`;
  const lines = разделы(d);

  // Сколько места остаётся сигналам во ВСЕХ разрешённых частях: блок считает
  // бюджет одним числом, а сообщений у сводки несколько.
  const room = Math.max(1, TG_BUDGET - title.length - " (продолжение)".length - 2);
  const занято = lines.reduce((n, l) => n + l.length + 1, 0);
  const budget = Math.max(0, WEEKLY_MAX_PARTS * room - занято - CHUNK_SLACK);
  const block = formatBriefingNotes(notes, NOTES_LIMIT, budget, WEEKLY_NOTES_HEADER);
  if (block) lines.push("", ...block.text.split("\n"));

  const parts = chunk(title, lines);
  if (parts.length <= WEEKLY_MAX_PARTS) return { parts, shownKeys: block?.shownKeys ?? [] };
  // Не влезло: печатаем обрезанную сводку и НЕ отмечаем ни одного сигнала —
  // срезан именно их хвост, а отметка необратима.
  return { parts: capped(title, lines, "Снек", WEEKLY_MAX_PARTS, "вкладке"), shownKeys: [] };
}
