/**
 * «Побыть сотрудником» — владелец смотрит на бота глазами полевого.
 *
 * Зачем: владелец идёт в боте своей веткой (сводки, согласования, вопросы), и
 * меню сотрудника ему не показывается вовсе. Проверить полевой поток перед
 * раздачей людям было нельзя иначе как заводить второй аккаунт в Telegram —
 * плохой обмен за проверку того, что сам же и раздаёшь.
 *
 * Формулировки взяты житейские, а не командные: владелец пишет «я сотрудник»,
 * а не «/staff». Команду со слэшем надо помнить, фразу — нет.
 *
 * Режим живёт в памяти процесса и гаснет при перезапуске (а он бывает на каждом
 * выкате). Для проверки это правильно: забыть выйти и однажды не получить
 * согласование — хуже, чем лишний раз написать «я сотрудник».
 */

const ON = /^(я\s+сотрудник|режим\s+сотрудника|как\s+сотрудник|побыть\s+сотрудником)$/i;
const OFF = /^(я\s+владелец|режим\s+владельца|обычный\s+режим|выйти\s+из\s+режима\s+сотрудника)$/i;

/**
 * Сообщение переключает режим? Тогда переключает и возвращает `true` —
 * вызывающему остаётся отчитаться человеку. Всё прочее не трогаем.
 *
 * Точное совпадение, а не `includes`: фраза «я сотрудник склада» в свободном
 * вопросе владельца не должна молча менять режим работы бота.
 */
export function asStaffMode(chatId: number, text: string, mode: Set<number>): boolean {
  const t = text.trim();
  if (ON.test(t)) {
    mode.add(chatId);
    return true;
  }
  if (OFF.test(t)) {
    mode.delete(chatId);
    return true;
  }
  return false;
}
